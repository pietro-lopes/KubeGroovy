private object KubeGroovyCompletionSupport {
	fun addCompletions(parameters: CompletionParameters, result: CompletionResultSet) {
		val bindingPrefix = supportBindingReferencePrefix(parameters)
		if (bindingPrefix != null) {
			val file = parameters.originalFile
			val bindings = supportScriptBindings(file)
			val completionBindings = bindings.map { it.name to it }.toMutableList()
			for (groupName in supportScriptEventMethods(file).map { it.groupName }.distinct()) {
				val bindingName = "\u0024${groupName}"
				if (completionBindings.none { it.first == bindingName }) {
					completionBindings += bindingName to KubeGroovyBinding(
						bindingName,
						KubeGroovyNames.EVENT_GROUP_BINDING,
						false,
						true
					)
				}
			}
			val startupEvents = bindings.firstOrNull { it.name == KubeGroovyNames.STARTUP_EVENTS }
				?: if (supportScriptTypeFor(file) == null || supportScriptTypeFor(file) == "startup") {
					KubeGroovyBinding(
						KubeGroovyNames.STARTUP_EVENTS,
						KubeGroovyNames.EVENT_GROUP_BINDING,
						false,
						true
					)
				} else null
			startupEvents?.let {
				if (completionBindings.none { binding -> binding.first == KubeGroovyNames.STARTUP_EVENTS }) {
					completionBindings += KubeGroovyNames.STARTUP_EVENTS to it
				}
				completionBindings += KubeGroovyNames.STARTUP_EVENTS_ALIAS to it
			}
			val bindingResults = result.withPrefixMatcher(bindingPrefix)
			for ((name, binding) in completionBindings.distinctBy { it.first }) {
				bindingResults.addElement(
					LookupElementBuilder.create(name)
						.withTypeText(supportScriptBindingType(binding), true)
						.withTailText("  KubeGroovy binding", true)
						.withKubeGroovyPriority()
				)
			}
		}
		supportAddBoundMemberCompletions(parameters, result)
		if (supportIsStartupRegistryTarget(parameters.position)) {
			val withPrefix = result.withPrefixMatcher(supportStringPrefix(parameters))
			KubeGroovyScriptData.registryTargets.forEach { target ->
				withPrefix.addElement(
					LookupElementBuilder.create(target.key)
						.withTypeText("String", true)
						.withTailText(" (RegistryKubeEvent<${target.elementTypeName}>)", true)
						.withInsertHandler { insertion, element -> supportInsertRegistryString(insertion, element) }
						.withKubeGroovyPriority()
				)
			}
		}
		result.runRemainingContributors(parameters) { candidate ->
			if (!supportShouldSuppressRawMethod(parameters, candidate.lookupElement.psiElement)) {
				result.passResult(candidate)
			}
		}
	}

	fun supportIsStartupRegistryTarget(position: PsiElement): Boolean {
		val call = PsiTreeUtil.getParentOfType(position, GrCall::class.java, false) as? GrMethodCallExpression ?: return false
		val reference = call.invokedExpression as? GrReferenceExpression ?: return false
		if (reference.referenceName != "registry") return false
		val qualifier = reference.qualifierExpression ?: return false
		if (qualifier.text != KubeGroovyNames.STARTUP_EVENTS && qualifier.text != KubeGroovyNames.STARTUP_EVENTS_ALIAS) return false
		val arguments = call.argumentList.expressionArguments
		if (arguments.isEmpty()) return false
		val targetRange = arguments[0].textRange
		return targetRange.contains(position.textRange) || targetRange.contains(position.textOffset)
	}

	fun supportScriptBindings(file: PsiFile): List<KubeGroovyBinding> =
