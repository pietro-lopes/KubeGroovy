class RegistryTargetTypedHandler : TypedHandlerDelegate() {
	override fun charTyped(charTyped: Char, project: Project, editor: Editor, file: PsiFile): Result {
		val offset = editor.caretModel.offset
		if (offset == 0) return Result.CONTINUE
		val position = file.findElementAt(offset - 1)
		val isStringDelimiter = charTyped == '\'' || charTyped == '"'
		val isIdentifierCharacter = charTyped.isLetterOrDigit() || charTyped in setOf('_', '-', ':', '/', '.', '#', '$') || isStringDelimiter
		if (!isIdentifierCharacter && (position == null || !kubeGroovyCompletionSupport.supportIsCatalogValueArgument(position))) return Result.CONTINUE
		if (position != null && (kubeGroovyCompletionSupport.supportIsStartupRegistryTarget(position)
				|| kubeGroovyCompletionSupport.supportIsBuilderTypeArgument(position)
				|| kubeGroovyCompletionSupport.supportIsCatalogValueArgument(position)
				|| bindingReferencePrefixAt(position, file, offset) != null)) {
			AutoPopupController.getInstance(project).scheduleAutoPopup(editor)
		}
		return Result.CONTINUE
	}

	private fun bindingReferencePrefixAt(position: PsiElement, file: PsiFile, offset: Int): String? {
		val reference = PsiTreeUtil.getParentOfType(position, GrReferenceExpression::class.java, false) ?: return null
		if (reference.qualifierExpression != null) return null
		val range = reference.referenceNameElement?.textRange ?: return null
		if (offset < range.startOffset || offset > range.endOffset) return null
		val prefix = file.text.substring(range.startOffset, offset)
		if (prefix.length <= 1) return null
		return prefix.takeIf { kubeGroovyCompletionSupport.supportHasBindingPrefix(file, it) }
	}
}

class ScriptBindingAnnotator : Annotator {
	private val bindingAttributes = TextAttributesKey.createTextAttributesKey(
		"KUBEGROOVY_SCRIPT_BINDING",
		DefaultLanguageHighlighterColors.CLASS_NAME
	)

	override fun annotate(element: PsiElement, holder: AnnotationHolder) {
		val literal = element as? GrLiteral
		if (literal != null) {
			kubeGroovyCompletionSupport.supportAnnotateValue(literal, holder)
			return
		}
		val reference = element as? GrReferenceExpression ?: return
		if (reference.qualifierExpression != null) return
		val name = reference.referenceName ?: return
		val isBinding = kubeGroovyCompletionSupport.supportScriptBindings(element.containingFile).any { it.name == name }
			|| (name == KubeGroovyNames.STARTUP_EVENTS_ALIAS
				&& kubeGroovyCompletionSupport.supportScriptBindings(element.containingFile).any { it.name == KubeGroovyNames.STARTUP_EVENTS })
		if (!isBinding) return
		val nameElement = reference.referenceNameElement ?: return
		holder.newSilentAnnotation(HighlightSeverity.INFORMATION)
			.range(nameElement.textRange)
			.textAttributes(bindingAttributes)
			.create()
	}
}

private class KubeGroovyExtensionClassLoader(
	parent: ClassLoader,
	private val generatedClasses: Map<String, ByteArray>
) : ClassLoader(parent) {
	override fun findClass(name: String): Class<*> {
		val bytes = generatedClasses[name] ?: return super.findClass(name)
		return defineClass(name, bytes, 0, bytes.size)
	}
}

private fun supportCreateDelegateClass(
	className: String,
	superName: String,
	delegateDescriptor: String,
	delegatedMethod: String,
	methodDescriptor: String,
	argumentLocals: List<Pair<Int, Int>>,
	returnOpcode: Int
): ByteArray {
	val owner = className.replace('.', '/')
	val parent = superName.replace('.', '/')
	val writer = ClassWriter(ClassWriter.COMPUTE_MAXS)
	writer.visit(Opcodes.V1_8, Opcodes.ACC_PUBLIC or Opcodes.ACC_SUPER, owner, null, parent, null)
	writer.visitField(
		Opcodes.ACC_PUBLIC or Opcodes.ACC_STATIC or Opcodes.ACC_VOLATILE,
		"delegate", delegateDescriptor, null, null
	).visitEnd()
	val constructor = writer.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null)
	constructor.visitCode()
	constructor.visitVarInsn(Opcodes.ALOAD, 0)
	constructor.visitMethodInsn(Opcodes.INVOKESPECIAL, parent, "<init>", "()V", false)
	constructor.visitInsn(Opcodes.RETURN)
	constructor.visitMaxs(0, 0)
	constructor.visitEnd()
	val method = writer.visitMethod(Opcodes.ACC_PUBLIC, delegatedMethod, methodDescriptor, null, null)
	method.visitCode()
	method.visitFieldInsn(Opcodes.GETSTATIC, owner, "delegate", delegateDescriptor)
	for ((opcode, local) in argumentLocals) method.visitVarInsn(opcode, local)
	method.visitMethodInsn(Opcodes.INVOKEVIRTUAL, parent, delegatedMethod, methodDescriptor, false)
	method.visitInsn(returnOpcode)
	method.visitMaxs(0, 0)
	method.visitEnd()
	writer.visitEnd()
	return writer.toByteArray()
}

