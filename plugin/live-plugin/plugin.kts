		val targetTypes: List<List<String>> = when {
			targetTypeName == null -> listOf(emptyList())
			eventMethod.targetRequired -> listOf(listOf("java.lang.String"), listOf(targetTypeName))
			else -> listOf(emptyList(), listOf("java.lang.String"), listOf(targetTypeName))
		}.distinct()
