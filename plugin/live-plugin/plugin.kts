class RegistryTargetCompletionConfidence : CompletionConfidence() {
	override fun shouldSkipAutopopup(editor: Editor, element: PsiElement, file: PsiFile, offset: Int): ThreeState =
		if (KubeGroovyCompletionSupport.supportIsStartupRegistryTarget(element)) ThreeState.NO else ThreeState.UNSURE
}

class RegistryTargetTypedHandler : TypedHandlerDelegate() {
	override fun charTyped(charTyped: Char, project: Project, editor: Editor, file: PsiFile): Result {
		if (!charTyped.isLetterOrDigit() && charTyped != '_' && charTyped != '-' && charTyped != '$') return Result.CONTINUE
		val offset = editor.caretModel.offset
		if (offset == 0) return Result.CONTINUE
		val position = file.findElementAt(offset - 1)
		if (position != null && (KubeGroovyCompletionSupport.supportIsStartupRegistryTarget(position)
				|| bindingReferencePrefixAt(position, file, offset) != null)) {
			AutoPopupController.getInstance(project).scheduleAutoPopup(editor)
		}
		return Result.CONTINUE
	}

	private fun bindingReferencePrefixAt(position: PsiElement, file: PsiFile, offset: Int): String? {
		val reference = PsiTreeUtil.getParentOfType(position, GrReferenceExpression::class.java, false) ?: return null
		if (reference.qualifierExpression != null) return null
		val range = reference.referenceNameElement?.textRange ?: return null
		if (offset < range.startOffset || offset > range.endOffset) return null
		val prefix = file.text.substring(range.startOffset, offset)
		if (prefix.length <= 1) return null
		return prefix.takeIf { KubeGroovyCompletionSupport.supportHasBindingPrefix(file, it) }
	}
}

class ScriptBindingAnnotator : Annotator {
	private val bindingAttributes = TextAttributesKey.createTextAttributesKey(
		"KUBEGROOVY_SCRIPT_BINDING",
		DefaultLanguageHighlighterColors.CLASS_NAME
	)

	override fun annotate(element: PsiElement, holder: AnnotationHolder) {
		val reference = element as? GrReferenceExpression ?: return
		if (reference.qualifierExpression != null) return
		val name = reference.referenceName ?: return
		val isBinding = KubeGroovyCompletionSupport.supportScriptBindings(element.containingFile).any { it.name == name }
			|| (name == KubeGroovyNames.STARTUP_EVENTS_ALIAS
				&& KubeGroovyCompletionSupport.supportScriptBindings(element.containingFile).any { it.name == KubeGroovyNames.STARTUP_EVENTS })
		if (!isBinding) return
		val nameElement = reference.referenceNameElement ?: return
		holder.newSilentAnnotation(HighlightSeverity.INFORMATION)
			.range(nameElement.textRange)
			.textAttributes(bindingAttributes)
			.create()
	}
}

