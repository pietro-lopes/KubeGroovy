class ScriptApiMembersContributor : NonCodeMembersContributor() {
	override fun processDynamicElements(
		qualifierType: PsiType,
		processor: PsiScopeProcessor,
		place: PsiElement,
		state: ResolveState
	) {
		val reference = place as? GrReferenceExpression ?: return
		val qualifier = reference.qualifierExpression
		val qualifierClassType = qualifierType as? PsiClassType ?: return
		val receiverClass = qualifierClassType.resolve() ?: return
		val receiverType = (if (receiverClass.qualifiedName == "java.lang.Class") {
			(qualifierClassType.parameters.singleOrNull() as? PsiClassType)?.resolve()?.qualifiedName
		} else receiverClass.qualifiedName) ?: return
		val isClassQualifier = qualifier == null
			|| receiverClass.qualifiedName == "java.lang.Class"
			|| (qualifier as? GrReferenceExpression)?.reference?.resolve() is PsiClass
		val nameHint = processor.getHint(NameHint.KEY)
		val name = reference.referenceName ?: return
		if (nameHint != null && nameHint.getName(state) != name) return

		val project = place.project
		val scope = place.resolveScope
		val containingClass = JavaPsiFacade.getInstance(project).findClass(receiverType, scope) ?: return
		val factory = JavaPsiFacade.getElementFactory(project)
		if (accepts(processor, ElementClassHint.DeclarationKind.METHOD)) {
			for (member in KubeGroovyScriptData.members) {
				if (member.receiverType != receiverType || member.name != name) continue
				if (qualifier == null && !member.constructor) continue
				if (member.constructor) {
					if (!isClassQualifier) continue
				} else if (isClassQualifier != member.isStatic) continue
				val method = GrLightMethodBuilder(place.manager, member.name)
				method.containingClass = containingClass
				if (member.constructor) method.setConstructor(true)
				method.setModifiers(if (member.isStatic) arrayOf(PsiModifier.PUBLIC, PsiModifier.STATIC) else arrayOf(PsiModifier.PUBLIC))
				for (typeParameter in member.typeParameters) method.addTypeParameter(typeParameter as String)
				method.returnType = factory.createTypeFromText(member.returnType, method)
				for ((index, parameterType) in member.parameters.withIndex()) {
					method.addParameter(GrLightParameter("arg$index", factory.createTypeFromText(parameterType, method), method))
				}
				processor.execute(method, state)
			}
			kubeGroovyCompletionSupport.supportAddStringCoercionMethods(
				reference, containingClass, isClassQualifier, processor, state
			)
		}
		if (qualifier != null && accepts(processor, ElementClassHint.DeclarationKind.VARIABLE, ElementClassHint.DeclarationKind.FIELD)) {
			for (property in KubeGroovyScriptData.properties) {
				if (property.receiverType != receiverType || property.name != name || isClassQualifier != property.isStatic) continue
				val implicitProperty = GrDynamicImplicitProperty(
					PsiManager.getInstance(place.project),
					property.name,
					property.type,
					property.type
				)
				ResolveUtil.processElement(processor, implicitProperty, state)
			}
		}
	}
}

private fun eventGroupName(file: PsiFile, qualifierText: String): String? {
	if (qualifierText == KubeGroovyNames.STARTUP_EVENTS_ALIAS) return "StartupEvents"
	if (qualifierText == KubeGroovyNames.STARTUP_EVENTS) return "StartupEvents"
	return scriptBindings(file).firstOrNull { binding ->
		binding.eventGroup && (binding.name == qualifierText || binding.name.removePrefix("\u0024") == qualifierText)
	}?.name?.removePrefix("\u0024")
}

class RegistryEventClosureParameterEnhancer : GrVariableEnhancer() {
	override fun getVariableType(variable: GrVariable): PsiType? {
		val parameter = variable as? GrParameter ?: return null
		val closure = PsiTreeUtil.getParentOfType(variable, GrClosableBlock::class.java, false) ?: return null
		val parameters = closure.allParameters
		if (parameters.isEmpty() || parameters[0] != parameter) return null

		val call = PsiTreeUtil.getParentOfType(closure, GrCall::class.java, false) as? GrMethodCallExpression ?: return null
		if (!isStartupRegistryCall(call)) return null
		val arguments = call.argumentList.expressionArguments
		if (arguments.isEmpty()) return null
		val target = registryTarget(arguments[0]) ?: return null

		val factory = JavaPsiFacade.getElementFactory(variable.project)
		return factory.createTypeFromText("${KubeGroovyNames.EVENT_TYPE}<${target.elementTypeName}>", variable)
	}

	private fun isStartupRegistryCall(call: GrMethodCallExpression): Boolean {
		val reference = call.invokedExpression as? GrReferenceExpression ?: return false
		if (reference.referenceName != "registry") return false
		val qualifier = reference.qualifierExpression ?: return false
		return qualifier.text == KubeGroovyNames.STARTUP_EVENTS || qualifier.text == KubeGroovyNames.STARTUP_EVENTS_ALIAS
	}

}

private fun registryTargetForKey(key: String): KubeGroovyRegistryTarget? {
	val normalizedKey = if (key.contains(":")) key else "minecraft:$key"
	return KubeGroovyScriptData.registryTargets.firstOrNull { it.key == normalizedKey }
}

private fun registryTargetForElementType(elementTypeName: String): KubeGroovyRegistryTarget? =
	KubeGroovyScriptData.registryTargets.firstOrNull { it.elementTypeName == elementTypeName.replace('$', '.') }

private fun registryTarget(target: GrExpression): KubeGroovyRegistryTarget? {
	val targetType = target.type as? PsiClassType
	val targetClassName = targetType?.resolve()?.qualifiedName
	if (targetClassName == KubeGroovyNames.RESOURCE_KEY) {
		val valueType = targetType.parameters.singleOrNull() as? PsiClassType
		val valueClass = valueType?.resolve()?.qualifiedName
		if (valueClass == KubeGroovyNames.REGISTRY) {
			val elementTypeName = valueType.parameters.singleOrNull()?.canonicalText
			val registryTarget = elementTypeName?.let(::registryTargetForElementType)
			if (registryTarget != null) return registryTarget
		} else {
			val registryTarget = valueType?.canonicalText?.let(::registryTargetForElementType)
			if (registryTarget != null) return registryTarget
		}
	}

	val literal = (target as? GrLiteral)
		?: PsiTreeUtil.findChildOfType(target, GrLiteral::class.java)
		?: return null
	val value = literal.value
	if (value is String) return registryTargetForKey(value)

	val text = literal.text
	if (text.length < 2) return null
	val quote = text.first()
	if ((quote != '\'' && quote != '"') || text.last() != quote) return null
	val key = text.substring(1, text.length - 1)
	return if ('\\' in key) null else registryTargetForKey(key)
}

private fun registryTargetForCreateCall(call: GrMethodCallExpression, eventElementType: PsiType): KubeGroovyRegistryTarget? {
	var current: PsiElement? = call.parent
	while (current != null) {
		val enclosingCall = current as? GrMethodCallExpression
		if (enclosingCall != null) {
			val reference = enclosingCall.invokedExpression as? GrReferenceExpression
			val qualifier = reference?.qualifierExpression
			if (reference?.referenceName == "registry"
				&& (qualifier?.text == KubeGroovyNames.STARTUP_EVENTS || qualifier?.text == KubeGroovyNames.STARTUP_EVENTS_ALIAS)
			) {
				val targetExpression = enclosingCall.argumentList.expressionArguments.firstOrNull()
				if (targetExpression != null) {
					registryTarget(targetExpression)?.let { return it }
				}
			}
		}
		current = current?.parent
	}
	return registryTargetForElementType(eventElementType.canonicalText)
}

private fun requestedBuilderTypeId(expression: GrExpression): String? {
	val literal = (expression as? GrLiteral) ?: PsiTreeUtil.findChildOfType(expression, GrLiteral::class.java) ?: return null
	val value = literal.value as? String ?: return null
	return if (value.contains(':')) value else "kubegroovy:$value"
}

private fun builderTypeFor(target: KubeGroovyRegistryTarget, requestedTypeId: String?): KubeGroovyBuilderType? {
	val registryBuilderTypes = KubeGroovyScriptData.builderTypes.filter { it.registryKey == target.key }
	if (requestedTypeId == null || requestedTypeId == "kubegroovy:default" || requestedTypeId.substringAfter(':') == "default") {
		return registryBuilderTypes.firstOrNull { it.defaultType }
	}
	return registryBuilderTypes.firstOrNull { !it.defaultType && it.typeId == requestedTypeId }
		?: registryBuilderTypes.firstOrNull {
			!it.defaultType && it.typeId.substringAfter(':') == requestedTypeId.substringAfter(':')
		}
}

class RegistryBuilderCallTypeCalculator : GrCallTypeCalculator {
	override fun getType(
		type: PsiType?,
		method: PsiMethod,
		arguments: List<Argument>?,
		place: PsiElement
	): PsiType? {
		if (method.name != "create" || method.containingClass?.qualifiedName != KubeGroovyNames.EVENT_TYPE) return null
		val call = (place as? GrMethodCallExpression)
			?: PsiTreeUtil.getParentOfType(place, GrMethodCallExpression::class.java, false)
			?: return null
		val reference = call.invokedExpression as? GrReferenceExpression ?: return null
		if (reference.referenceName != "create") return null
		val receiverType = reference.qualifierExpression?.type as? PsiClassType ?: return null
		if (receiverType.resolve()?.qualifiedName != KubeGroovyNames.EVENT_TYPE) return null
		val eventElementType = receiverType.parameters.singleOrNull() ?: return null
		val target = registryTargetForCreateCall(call, eventElementType) ?: return null
		val expressions = call.argumentList.expressionArguments
		val typeExpression = expressions.getOrNull(1)
		val requestedTypeId = if (typeExpression == null) null else requestedBuilderTypeId(typeExpression) ?: return null
		val builderType = builderTypeFor(target, requestedTypeId) ?: return null
		val builderClass = JavaPsiFacade.getInstance(place.project).findClass(builderType.builderTypeName, place.resolveScope)
		return builderClass?.let { JavaPsiFacade.getElementFactory(place.project).createType(it) }
	}
}

