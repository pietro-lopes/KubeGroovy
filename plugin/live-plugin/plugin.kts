private class KubeGroovyCompletionSupport {
	private fun supportIsStringLiteralArgument(expression: GrExpression): Boolean {
		val literal = expression as? GrLiteral ?: return false
		val text = literal.text
		if (text.isEmpty() || text.first() !in listOf('"', '\'')) return false
		if (text.startsWith("\"\"\"") || text.startsWith("'''")) return false
		return literal.value == null || literal.value is String
	}

	private fun supportCanConvertString(type: PsiType, context: PsiElement): Boolean {
		val resolved = (type as? PsiClassType)?.resolve() ?: return false
		val name = resolved.qualifiedName?.replace('$', '.') ?: return false
		return resolved.isEnum || name in kubeGroovyValueCatalog.stringWrappers
			|| supportTargetForType(type, context) != null
	}

	fun supportAddStringCoercionMethods(
		reference: GrReferenceExpression,
		receiverClass: PsiClass,
		isClassQualifier: Boolean,
		processor: PsiScopeProcessor,
		state: ResolveState
	) {
		if (scriptTypeFor(reference.containingFile) == null) return
		if (!accepts(processor, ElementClassHint.DeclarationKind.METHOD)) return
		val name = reference.referenceName ?: return
		val call = PsiTreeUtil.getParentOfType(reference, GrMethodCallExpression::class.java, false) ?: return
		if (call.invokedExpression != reference || call.argumentList.namedArguments.isNotEmpty()) return
		val arguments = call.argumentList.expressionArguments
		if (arguments.isEmpty()) return
		val stringType = PsiType.getJavaLangString(reference.manager, reference.resolveScope)
		val emittedSignatures = mutableSetOf<String>()
		for (sourceMethod in receiverClass.findMethodsByName(name, true)) {
			if (!sourceMethod.hasModifierProperty(PsiModifier.PUBLIC)
				|| sourceMethod.isConstructor
				|| sourceMethod.isVarArgs
				|| sourceMethod.typeParameters.isNotEmpty()
				|| sourceMethod.hasModifierProperty(PsiModifier.STATIC) != isClassQualifier) continue
			val sourceParameters = sourceMethod.parameterList.parameters
			if (sourceParameters.size != arguments.size) continue
			val adaptedPositions = sourceParameters.indices.filter { index ->
				supportIsStringLiteralArgument(arguments[index])
					&& supportCanConvertString(sourceParameters[index].type, reference)
			}
			if (adaptedPositions.isEmpty()) continue
			val signature = sourceParameters.mapIndexed { index, parameter ->
				if (index in adaptedPositions) "java.lang.String" else parameter.type.canonicalText.replace('$', '.')
			}.joinToString(",")
			if (!emittedSignatures.add("$name($signature)")) continue

			val adapted = GrLightMethodBuilder(reference.manager, name)
			adapted.containingClass = receiverClass
			adapted.setModifiers(if (isClassQualifier) arrayOf(PsiModifier.PUBLIC, PsiModifier.STATIC) else arrayOf(PsiModifier.PUBLIC))
			adapted.returnType = sourceMethod.returnType ?: PsiTypes.voidType()
			adapted.navigationElement = sourceMethod
			for ((index, parameter) in sourceParameters.withIndex()) {
				val type = if (index in adaptedPositions) stringType else parameter.type
				adapted.addParameter(GrLightParameter(parameter.name, type, adapted))
			}
			processor.execute(adapted, state)
		}
	}

	private fun LookupElement.withKubeGroovyPriority(): LookupElement =
		PrioritizedLookupElement.withPriority(this, 1000.0)

	private fun supportTypeName(type: PsiType): String? =
		(type as? PsiClassType)?.resolve()?.qualifiedName?.replace('$', '.')

	private fun supportTypeArguments(type: PsiType): List<PsiType> = (type as? PsiClassType)?.parameters?.toList().orEmpty()

	private fun supportStringType(text: String, context: PsiElement): PsiType? =
		runCatching { JavaPsiFacade.getElementFactory(context.project).createTypeFromText(text, context) }.getOrNull()

	private fun supportRegistryForElementType(typeName: String): List<KubeGroovyCatalogRegistry> {
		val normalized = typeName.replace('$', '.')
		return kubeGroovyValueCatalog.registries.filter { it.elementType.replace('$', '.') == normalized }
	}

	private fun supportIdDisplay(id: String): String = id.removePrefix("minecraft:")

	private fun supportRegistryValues(typeName: String): KubeGroovyValueTarget? {
		val matching = supportRegistryForElementType(typeName)
		if (matching.isEmpty()) return null
		val entries = matching.flatMap { it.entries }.distinct().sorted()
		val tags = matching.flatMap { it.tags }.distinct().sorted()
		return KubeGroovyValueTarget(
			KubeGroovyValueMode.EXISTING,
			entries.map(::supportIdDisplay),
			entries.toSet(),
			tags.toSet()
		)
	}

	private fun supportTagTarget(typeName: String): KubeGroovyValueTarget? {
		val matching = supportRegistryForElementType(typeName)
		if (matching.isEmpty()) return null
		val tags = matching.flatMap { it.tags }.distinct().sorted()
		return KubeGroovyValueTarget(KubeGroovyValueMode.TAG_KEY, tags.map(::supportIdDisplay), knownTags = tags.toSet())
	}

	private fun supportWithTagSuggestions(target: KubeGroovyValueTarget): KubeGroovyValueTarget =
		target.copy(
			mode = KubeGroovyValueMode.EXISTING_OR_TAG,
			suggestions = (target.suggestions + target.knownTags.map { "#$it" }).distinct().sorted()
		)

	private fun supportTargetForType(type: PsiType, context: PsiElement, depth: Int = 0): KubeGroovyValueTarget? {
		if (depth > 8 || type.canonicalText == "?" || type.canonicalText == "T" || type.canonicalText.contains("<unknown")) return null
		val className = supportTypeName(type) ?: return null
		val arguments = supportTypeArguments(type)
		when (className) {
			"java.util.Optional" -> return arguments.singleOrNull()?.let { supportTargetForType(it, context, depth + 1) }
			"net.minecraft.resources.ResourceKey" -> {
				val keyType = arguments.singleOrNull() ?: return null
				if (supportTypeName(keyType) == KubeGroovyNames.REGISTRY) {
					val elementType = supportTypeArguments(keyType).singleOrNull()
					val registries = if (elementType == null || elementType.canonicalText == "?"
						|| elementType.canonicalText == "java.lang.Object") {
						kubeGroovyValueCatalog.registries
					} else supportRegistryForElementType(elementType.canonicalText)
					val keys = registries.map { it.key }.distinct().sorted()
					return KubeGroovyValueTarget(KubeGroovyValueMode.RESOURCE_KEY, keys.map(::supportIdDisplay), keys.toSet())
				}
				val matching = supportRegistryForElementType(keyType.canonicalText)
				if (matching.isEmpty()) return null
				val keys = matching.flatMap { it.entries }.distinct().sorted()
				return KubeGroovyValueTarget(KubeGroovyValueMode.RESOURCE_KEY, keys.map(::supportIdDisplay), keys.toSet())
			}
			"net.minecraft.core.Holder",
			"net.minecraft.core.Holder.Reference" -> return arguments.singleOrNull()?.let { supportRegistryValues(it.canonicalText) }
			"net.minecraft.core.HolderSet" -> {
				val element = arguments.singleOrNull() ?: return null
				val target = supportRegistryValues(element.canonicalText) ?: return null
				return supportWithTagSuggestions(target)
			}
			"net.minecraft.tags.TagKey" -> return arguments.singleOrNull()?.let { supportTagTarget(it.canonicalText) }
			"dev.uncandango.kubegroovy.util.registrypredicate.RegistryPredicate" -> {
