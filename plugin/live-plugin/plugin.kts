class RegistryTargetCompletionConfidence : CompletionConfidence() {
	override fun shouldSkipAutopopup(editor: Editor, element: PsiElement, file: PsiFile, offset: Int): ThreeState =
		if (kubeGroovyCompletionSupport.supportIsStartupRegistryTarget(element)
			|| kubeGroovyCompletionSupport.supportIsBuilderTypeArgument(element)
			|| kubeGroovyCompletionSupport.supportIsCatalogValueArgument(element)
		) ThreeState.NO else ThreeState.UNSURE
}

