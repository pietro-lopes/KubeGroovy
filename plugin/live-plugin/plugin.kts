			"net.minecraft.world.level.block.SoundType" -> return KubeGroovyValueTarget(
				KubeGroovyValueMode.EXISTING, kubeGroovyValueCatalog.soundTypes,
				kubeGroovyValueCatalog.soundTypes.toSet()
