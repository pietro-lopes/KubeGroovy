private fun scriptTypeFor(file: PsiFile): String? {
	val path = (file.virtualFile?.path ?: file.originalFile.virtualFile?.path)
		?.replace('\\', '/')
		?.lowercase(Locale.ROOT)
		?: return null
	val normalizedPath = "/$path/"
	return listOf("startup", "server", "client").firstOrNull { "/${it}_scripts/" in normalizedPath }
}

private fun scriptBindings(file: PsiFile): List<KubeGroovyBinding> =
	scriptTypeFor(file)?.let(KubeGroovyScriptData.bindingsByScriptType::get)
		?: KubeGroovyScriptData.bindingsByScriptType.values.flatten().distinctBy { it.name }

private fun scriptEventMethods(file: PsiFile, groupName: String): List<KubeGroovyEventMethod> {
