			&& (binding != null || startupEventsAlias || referenceName == KubeGroovyNames.STARTUP_EVENTS)
			&& (nameHint == null || referenceName == nameHint.getName(state))
			&& accepts(processor, ElementClassHint.DeclarationKind.VARIABLE, ElementClassHint.DeclarationKind.FIELD)
		) {
			val type = binding?.let(::scriptBindingType) ?: KubeGroovyNames.EVENT_GROUP_BINDING
			val property = GrDynamicImplicitProperty(
				PsiManager.getInstance(place.project),
				referenceName,
				type,
				type
			)
			ResolveUtil.processElement(processor, property, state)
			return
		}

		val qualifier = reference.qualifierExpression ?: return
		val groupName = eventGroupName(place.containingFile, qualifier.text) ?: return
		if (!qualifierType.equalsToText(KubeGroovyNames.EVENT_GROUP_BINDING)) return
		if (nameHint != null && nameHint.getName(state) != referenceName) return
		if (!accepts(processor, ElementClassHint.DeclarationKind.METHOD)) return

		val project = place.project
		val bindingClass = JavaPsiFacade.getInstance(project).findClass(KubeGroovyNames.EVENT_GROUP_BINDING, place.resolveScope)
		val factory = JavaPsiFacade.getElementFactory(project)
		if (groupName != "StartupEvents" || referenceName != "registry") {
			for (eventMethod in scriptEventMethods(place.containingFile, groupName).filter { it.name == referenceName }) {
				addEventMethods(processor, state, place, bindingClass, factory, eventMethod)
			}
			return
		}

