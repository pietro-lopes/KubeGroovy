			val method = GrLightMethodBuilder(place.manager, eventMethod.name)
			method.returnType = PsiTypes.voidType()
			for (targetType in targets) {
				method.addParameter(GrLightParameter("target", factory.createTypeFromText(targetType, method), method))
			}
			val handlerType = "java.util.function.Consumer<${eventMethod.eventTypeName}>"
			method.addParameter(GrLightParameter("handler", factory.createTypeFromText(handlerType, method), method))
			if (bindingClass != null) method.containingClass = bindingClass
			processor.execute(method, state)
		}
	}
