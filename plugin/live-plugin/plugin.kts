			"dev.uncandango.kubegroovy.item.ItemTintFunction" -> {
				val values = (kubeGroovyValueCatalog.itemTintFunctions + kubeGroovyValueCatalog.colorNames).distinct().sorted()
				return KubeGroovyValueTarget(KubeGroovyValueMode.COLOR, values, values.toSet())
			}
			"dev.uncandango.kubegroovy.block.BlockTintFunction" -> {
