				return supportWithTagSuggestions(target)
			}
			"net.minecraft.world.item.crafting.Ingredient",
			"dev.uncandango.kubegroovy.item.ItemPredicate" -> {
				val target = supportRegistryValues("net.minecraft.world.item.Item") ?: return null
				return supportWithTagSuggestions(target)
			}
			"net.neoforged.neoforge.fluids.crafting.FluidIngredient" -> {
				val target = supportRegistryValues("net.minecraft.world.level.material.Fluid") ?: return null
				return supportWithTagSuggestions(target)
			}
			"dev.uncandango.kubegroovy.block.state.BlockStatePredicate" -> {
				val target = supportRegistryValues("net.minecraft.world.level.block.Block") ?: return null
				return supportWithTagSuggestions(target)
			}
			"net.minecraft.world.level.ItemLike",
			"net.minecraft.world.item.Item" -> return supportRegistryValues("net.minecraft.world.item.Item")
			"net.minecraft.world.level.block.Block" -> return supportRegistryValues(className)
			"net.minecraft.world.level.material.Fluid" -> return supportRegistryValues(className)
			"net.minecraft.world.item.ItemStack" -> return supportRegistryValues("net.minecraft.world.item.Item")
			"net.neoforged.neoforge.fluids.FluidStack" -> return supportRegistryValues("net.minecraft.world.level.material.Fluid")
			"net.minecraft.world.item.ToolMaterial" -> return KubeGroovyValueTarget(
				KubeGroovyValueMode.EXISTING, kubeGroovyValueCatalog.toolMaterials,
				kubeGroovyValueCatalog.toolMaterials.toSet()
