			GrLightParameter(
				"target",
				factory.createTypeFromText("${KubeGroovyNames.RESOURCE_KEY}<${KubeGroovyNames.REGISTRY}<$elementType>>", resourceKeyMethod),
				resourceKeyMethod
			)
		)
		resourceKeyMethod.addParameter(
			GrLightParameter(
				"handler",
				factory.createTypeFromText("java.util.function.Consumer<${KubeGroovyNames.EVENT_TYPE}<$elementType>>", resourceKeyMethod),
				resourceKeyMethod
			)
		)
		if (bindingClass != null) resourceKeyMethod.containingClass = bindingClass
		if (navigationElement != null) resourceKeyMethod.navigationElement = navigationElement
		processor.execute(resourceKeyMethod, state)

		val stringMethod = GrLightMethodBuilder(place.manager, "registry")
		stringMethod.returnType = PsiTypes.voidType()
		stringMethod.addParameter(
			GrLightParameter(
				"target",
				PsiType.getJavaLangString(place.manager, place.resolveScope),
				stringMethod
			)
		)
		stringMethod.addParameter(
			GrLightParameter(
				"handler",
				factory.createTypeFromText("java.util.function.Consumer<${KubeGroovyNames.EVENT_TYPE}<${target?.elementTypeName ?: "?"}>>", stringMethod),
				stringMethod
