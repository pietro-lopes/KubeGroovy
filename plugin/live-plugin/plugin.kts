		if (scriptType != null && scriptType != "startup") return false
		return KubeGroovyNames.STARTUP_EVENTS.startsWith(prefix, ignoreCase = true)
			|| KubeGroovyNames.STARTUP_EVENTS_ALIAS.startsWith(prefix, ignoreCase = true)
	}

