			return KubeGroovyValueTarget(KubeGroovyValueMode.ENUM, values, values.toSet())
		}
		return null
	}

	private fun supportContainerElementType(container: GrListOrMap, type: PsiType, literal: GrLiteral): PsiType? {
		val unwrappedType = if (supportTypeName(type) == "java.util.Optional") {
			supportTypeArguments(type).singleOrNull() ?: return null
		} else type
		val className = supportTypeName(unwrappedType)
		val arguments = supportTypeArguments(unwrappedType)
		if (container.isMap) {
			if (className != "java.util.Map" || arguments.size < 2) return null
			val childIsKey = supportMapLiteralIsKey(container, literal) ?: return null
			return arguments[if (childIsKey) 0 else 1]
		}
		if (unwrappedType is com.intellij.psi.PsiArrayType) return unwrappedType.componentType
		return when {
			className in setOf("java.util.List", "java.util.Collection", "java.util.Set", "java.lang.Iterable") -> arguments.singleOrNull()
			className == "net.minecraft.core.HolderSet" || className == "dev.uncandango.kubegroovy.util.registrypredicate.RegistryPredicate" -> arguments.singleOrNull()
			else -> null
		}
	}

	private fun supportMapLiteralIsKey(container: GrListOrMap, literal: GrLiteral): Boolean? {
		val text = container.text
		val relativeOffset = literal.textOffset - container.textRange.startOffset
		if (relativeOffset !in text.indices) return null
		var quote: Char? = null
		var escaped = false
		var square = 0
		var curly = 0
		var round = 0
		val separators = mutableListOf<Pair<Char, Int>>()
		for (index in 1 until text.length - 1) {
			val character = text[index]
			if (quote != null) {
				if (escaped) escaped = false
				else if (character == '\\') escaped = true
				else if (character == quote) quote = null
				continue
			}
			if (character == '\'' || character == '"') {
				quote = character
				continue
			}
			when (character) {
				'[' -> square++
				']' -> square--
				'{' -> curly++
				'}' -> curly--
				'(' -> round++
				')' -> round--
				':', ',' -> if (square == 0 && curly == 0 && round == 0) separators += character to index
			}
		}
		val start = separators.lastOrNull { it.first == ',' && it.second < relativeOffset }?.second?.plus(1) ?: 1
		val end = separators.firstOrNull { it.first == ',' && it.second > relativeOffset }?.second ?: (text.length - 1)
		val colons = separators.filter { it.first == ':' && it.second in start until end }
		if (colons.size != 1) return null
		return relativeOffset < colons.single().second
	}

	private fun supportExpectedTypes(position: PsiElement): List<PsiType>? {
		if (supportScriptTypeFor(position.containingFile) == null) return null
		val literal = PsiTreeUtil.getParentOfType(position, GrLiteral::class.java, false) ?: return null
		val literalText = literal.text
		if (literalText.isEmpty() || literalText.first() !in listOf('"', '\'')
			|| literalText.startsWith("\"\"\"") || literalText.startsWith("'''")) return null
		if (literal.value != null && literal.value !is String) return null
		val call = PsiTreeUtil.getParentOfType(literal, GrCall::class.java, false) ?: return null
		val argumentList = PsiTreeUtil.getParentOfType(literal, GrArgumentList::class.java, false)
			?: call.argumentList
			?: return null
		val arguments = argumentList.expressionArguments
		val positionalArgumentIndex = arguments.indexOfFirst { it.textRange.contains(literal.textRange) }
		val namedArgument = generateSequence(literal.parent as PsiElement?) { it.parent }
			.takeWhile { it != call }
			.filterIsInstance<GrNamedArgument>()
			.firstOrNull { it.expression?.textRange?.contains(literal.textRange) == true }
		val argumentIndex = if (positionalArgumentIndex >= 0) positionalArgumentIndex else if (namedArgument != null) 0 else -1
		if (argumentIndex < 0) return null
		val advancedResolution = runCatching { call.advancedResolve() }.getOrNull()
		val resolutions = (runCatching { call.multiResolveGroovy(false).toList() }.getOrDefault(emptyList())
			+ listOfNotNull(advancedResolution)).distinctBy { it.element }
		val resolution = resolutions.firstOrNull { it.isValidResult && it.isApplicable }
			?: advancedResolution?.takeIf { it.isValidResult }
			?: resolutions.firstOrNull { it.isValidResult }
			?: return null
		val method = resolution.element as? PsiMethod ?: return null
		val visibleParameter = method.parameterList.parameters.getOrNull(argumentIndex) ?: return null
		val semanticMethod = (method.navigationElement as? PsiMethod)?.takeIf { source ->
			source.isValid && source.name == method.name
				&& source.parameterList.parameters.size == method.parameterList.parameters.size
		} ?: method
		val parameter = semanticMethod.parameterList.parameters.getOrNull(argumentIndex) ?: visibleParameter
		val substituted = resolution.substitutor.substitute(parameter.type) ?: parameter.type
		if (positionalArgumentIndex >= 0 && !arguments[argumentIndex].textRange.contains(literal.textRange)) return null
		if (namedArgument != null && positionalArgumentIndex < 0 && supportTypeName(substituted) != "java.util.Map") return null
		val containers = generateSequence(literal.parent as PsiElement?) { it.parent }
			.takeWhile { it != arguments.getOrNull(argumentIndex) && it != namedArgument }
			.filterIsInstance<GrListOrMap>()
			.toList()
		var effectiveTypes = listOfNotNull(if (namedArgument != null && positionalArgumentIndex < 0) {
			supportTypeArguments(substituted).getOrNull(1)
		} else substituted)
		for (container in containers.asReversed()) {
			effectiveTypes = effectiveTypes.mapNotNull { supportContainerElementType(container, it, literal) }.distinctBy { it.canonicalText }
			if (effectiveTypes.isEmpty()) return null
		}
		val receiverClass = method.containingClass?.qualifiedName?.replace('$', '.') ?: return effectiveTypes
		val actualParameters = method.parameterList.parameters.map { it.type.canonicalText.replace('$', '.') }
		val matchingDescriptors = KubeGroovyScriptData.members.filter { member ->
			member.receiverType.replace('$', '.') == receiverClass
				&& member.name == method.name
				&& member.constructor == method.isConstructor
				&& member.parameters.size == actualParameters.size
				&& member.parameters.map { it.replace('$', '.') } == actualParameters
		}
		if (matchingDescriptors.isEmpty()) return effectiveTypes
		val semanticTypeNames = matchingDescriptors.flatMap { member ->
			member.semanticParameters.mapNotNull { it.getOrNull(argumentIndex) }
		}.distinct()
		if (semanticTypeNames.size != 1) return null
		val semanticType = supportStringType(semanticTypeNames.single(), method) ?: return null
		val substitutedSemantic = resolution.substitutor.substitute(semanticType) ?: semanticType
		var semanticTypes = listOfNotNull(if (namedArgument != null && positionalArgumentIndex < 0) {
			supportTypeArguments(substitutedSemantic).getOrNull(1)
		} else substitutedSemantic)
		for (container in containers.asReversed()) {
			semanticTypes = semanticTypes.mapNotNull { supportContainerElementType(container, it, literal) }.distinctBy { it.canonicalText }
			if (semanticTypes.isEmpty()) return null
		}
		return semanticTypes
	}

	private fun supportValueTarget(position: PsiElement): KubeGroovyValueTarget? {
		val expectedTypes = supportExpectedTypes(position) ?: return null
		val targets = expectedTypes.mapNotNull { type ->
			val target = supportTargetForType(type, position) ?: return@mapNotNull null
			if (type.canonicalText == "java.lang.String") return@mapNotNull null
			target
		}.distinctBy { target -> target.mode to target.suggestions }
		return targets.singleOrNull()
	}

	fun supportIsCatalogValueArgument(position: PsiElement): Boolean = supportValueTarget(position) != null

	fun supportAnnotateValue(literal: GrLiteral, holder: AnnotationHolder) {
		if (literal.text.length < 2 || literal.text.last() != literal.text.first()) return
		val target = supportValueTarget(literal) ?: return
		val value = literal.value as? String ?: return
		val validation = supportValidationMessage(target, value) ?: return
		holder.newAnnotation(validation.first, validation.second).range(literal.textRange).create()
	}

	private fun supportCanonicalId(value: String, defaultNamespace: String = "minecraft"): String =
		if (':' in value) value else "$defaultNamespace:$value"

	private fun supportIsValidIdentifier(value: String): Boolean {
		val pieces = value.split(':')
		if (pieces.size == 1) return pieces[0].matches(Regex("[a-z0-9/._-]+"))
		if (pieces.size != 2) return false
		return pieces[0].matches(Regex("[a-z0-9_.-]+")) && pieces[1].matches(Regex("[a-z0-9/._-]+"))
	}

	private fun supportValidationMessage(target: KubeGroovyValueTarget, value: String): Pair<HighlightSeverity, String>? {
		when (target.mode) {
			KubeGroovyValueMode.UUID -> {
			val normalized = if (value.length == 32) buildString {
				value.forEachIndexed { index, character ->
					append(character)
					if (index in setOf(7, 11, 15, 19)) append('-')
				}
			} else value
				val valid = value.length in setOf(32, 36) && runCatching { java.util.UUID.fromString(normalized) }.isSuccess
				return if (valid) null else HighlightSeverity.ERROR to "Invalid UUID: expected a 32- or 36-character UUID"
			}
			KubeGroovyValueMode.IDENTIFIER, KubeGroovyValueMode.KUBE_IDENTIFIER ->
				return if (supportIsValidIdentifier(value)) null else HighlightSeverity.ERROR to "Invalid identifier namespace or path"
			KubeGroovyValueMode.COLOR ->
				if (value.matches(Regex("#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?"))) return null
				else if (value in target.knownValues) return null
				else return HighlightSeverity.WEAK_WARNING to "Unknown color or tint name '$value'"
			KubeGroovyValueMode.ENUM ->
				return if (target.knownValues.any { it.equals(value, ignoreCase = true) }) null
				else HighlightSeverity.WEAK_WARNING to "Unknown enum value '$value'"
			KubeGroovyValueMode.RESOURCE_KEY, KubeGroovyValueMode.TAG_KEY ->
				return if (supportIsValidIdentifier(value)) null else HighlightSeverity.ERROR to "Invalid identifier namespace or path"
			KubeGroovyValueMode.FREE -> return null
			KubeGroovyValueMode.EXISTING, KubeGroovyValueMode.EXISTING_OR_TAG -> Unit
		}
		if (value.isBlank() || value in setOf("*", "-", "air", "minecraft:air") || value.startsWith('@') || value.startsWith('/')
			|| value.startsWith('%') || value.startsWith('[') || value.contains('{') || value.contains('[') || value.contains(' ')) return null
		if (value.startsWith('#')) {
			if (target.mode != KubeGroovyValueMode.EXISTING_OR_TAG) return null
			val tag = supportCanonicalId(value.removePrefix("#"))
			return if (tag in target.knownTags) null else HighlightSeverity.WEAK_WARNING to "Tag '$value' is not in the generated catalog"
		}
		val id = supportCanonicalId(value)
		if (id in target.knownValues) return null
		return HighlightSeverity.WEAK_WARNING to "Value '$value' is not in the generated catalog"
	}

	private fun supportAddValueCompletions(position: PsiElement, parameters: CompletionParameters, result: CompletionResultSet) {
		val target = supportValueTarget(position) ?: return
		val literal = PsiTreeUtil.getParentOfType(position, GrLiteral::class.java, false) ?: return
		val prefixResults = result.withPrefixMatcher(if (target.mode == KubeGroovyValueMode.UUID) "" else supportStringPrefix(parameters))
		val values = when (target.mode) {
			KubeGroovyValueMode.UUID -> listOf(java.util.UUID.randomUUID().toString())
			else -> target.suggestions
		}
		val tagMode = target.mode == KubeGroovyValueMode.TAG_KEY
		for (rawValue in values.distinct()) {
			val insertionValue = when {
				tagMode -> supportIdDisplay(rawValue)
				rawValue.startsWith('#') -> "#${supportIdDisplay(rawValue.removePrefix("#"))}"
				else -> supportIdDisplay(rawValue)
			}
			var lookup = LookupElementBuilder.create(insertionValue)
				.withTypeText(literal.type?.presentableText ?: "String", true)
				.withInsertHandler { insertion, _ -> supportInsertString(insertion, insertionValue) }
			val fullIdLookup = when {
				tagMode -> rawValue
				rawValue.startsWith('#') -> rawValue
				else -> rawValue
			}
			if (fullIdLookup != insertionValue) lookup = lookup.withLookupString(fullIdLookup)
			prefixResults.addElement(lookup.withKubeGroovyPriority())
		}
	}

	private fun registryTargetForKey(key: String): KubeGroovyRegistryTarget? {
		val normalizedKey = if (key.contains(":")) key else "minecraft:$key"
		return KubeGroovyScriptData.registryTargets.firstOrNull { it.key == normalizedKey }
	}

	fun addCompletions(parameters: CompletionParameters, result: CompletionResultSet) {
		val bindingPrefix = supportBindingReferencePrefix(parameters)
		if (bindingPrefix != null) {
			val file = parameters.originalFile
			val bindings = supportScriptBindings(file)
			val completionBindings = bindings.map { it.name to it }.toMutableList()
			for (groupName in supportScriptEventMethods(file).map { it.groupName }.distinct()) {
				val bindingName = "\u0024${groupName}"
				if (completionBindings.none { it.first == bindingName }) {
					completionBindings += bindingName to KubeGroovyBinding(
						bindingName,
						KubeGroovyNames.EVENT_GROUP_BINDING,
						false,
						true
					)
				}
			}
			val startupEvents = bindings.firstOrNull { it.name == KubeGroovyNames.STARTUP_EVENTS }
				?: if (supportScriptTypeFor(file) == null || supportScriptTypeFor(file) == "startup") {
					KubeGroovyBinding(
						KubeGroovyNames.STARTUP_EVENTS,
						KubeGroovyNames.EVENT_GROUP_BINDING,
						false,
						true
					)
				} else null
			startupEvents?.let {
				if (completionBindings.none { binding -> binding.first == KubeGroovyNames.STARTUP_EVENTS }) {
					completionBindings += KubeGroovyNames.STARTUP_EVENTS to it
				}
				completionBindings += KubeGroovyNames.STARTUP_EVENTS_ALIAS to it
			}
			val bindingResults = result.withPrefixMatcher(bindingPrefix)
			for ((name, binding) in completionBindings.distinctBy { it.first }) {
				bindingResults.addElement(
					LookupElementBuilder.create(name)
						.withTypeText(supportScriptBindingType(binding), true)
						.withTailText("  KubeGroovy binding", true)
						.withKubeGroovyPriority()
				)
			}
		}
		supportAddBoundMemberCompletions(parameters, result)
		if (supportIsStartupRegistryTarget(parameters.position)) {
			val withPrefix = result.withPrefixMatcher(supportStringPrefix(parameters))
			KubeGroovyScriptData.registryTargets.forEach { target ->
				val suggestedKey = target.key.removePrefix("minecraft:")
				val suggestion = LookupElementBuilder.create(suggestedKey)
				val lookupElement = if (target.key.startsWith("minecraft:")) {
					suggestion.withLookupString(target.key)
				} else suggestion
				withPrefix.addElement(
					lookupElement
						.withTypeText("String", true)
						.withTailText(" (RegistryKubeEvent<${target.elementTypeName}>)", true)
						.withInsertHandler { insertion, element -> supportInsertRegistryString(insertion, element) }
						.withKubeGroovyPriority()
				)
			}
		}
		supportBuilderTypeTarget(parameters.position)?.let { target ->
			val withPrefix = result.withPrefixMatcher(supportStringPrefix(parameters))
			val registryBuilderTypes = KubeGroovyScriptData.builderTypes
				.filter { it.registryKey == target.key }
			val options = mutableListOf<Pair<String, KubeGroovyBuilderType>>()
			registryBuilderTypes.firstOrNull { it.defaultType }?.let { options.add("default" to it) }
			options.addAll(registryBuilderTypes.asSequence()
				.filterNot { it.defaultType || it.typeId.substringAfter(':') == "default" }
				.sortedBy { it.typeId }
				.map { type ->
					val suggestedId = if (type.typeId.startsWith("kubegroovy:")) type.typeId.removePrefix("kubegroovy:") else type.typeId
					suggestedId to type
			}.toList())
			for ((suggestedId, builderType) in options.distinctBy { it.first }) {
				var suggestion = LookupElementBuilder.create(suggestedId)
					.withTypeText(builderType.builderTypeName, true)
					.withTailText(if (builderType.defaultType) "  default builder" else "  builder type", true)
					.withInsertHandler { insertion, _ -> supportInsertBuilderType(insertion, suggestedId) }
				if (builderType.typeId != suggestedId) suggestion = suggestion.withLookupString(builderType.typeId)
				withPrefix.addElement(suggestion.withKubeGroovyPriority())
			}
		}
		supportAddValueCompletions(parameters.position, parameters, result)
		result.runRemainingContributors(parameters) { candidate ->
			if (!supportShouldSuppressRawMethod(parameters, candidate.lookupElement.psiElement)) {
				result.passResult(candidate)
			}
		}
	}

	fun supportIsStartupRegistryTarget(position: PsiElement): Boolean {
		val call = PsiTreeUtil.getParentOfType(position, GrCall::class.java, false) as? GrMethodCallExpression ?: return false
		val reference = call.invokedExpression as? GrReferenceExpression ?: return false
		if (reference.referenceName != "registry") return false
		val qualifier = reference.qualifierExpression ?: return false
		if (qualifier.text != KubeGroovyNames.STARTUP_EVENTS && qualifier.text != KubeGroovyNames.STARTUP_EVENTS_ALIAS) return false
		val arguments = call.argumentList.expressionArguments
		if (arguments.isEmpty()) return false
		val targetRange = arguments[0].textRange
		return targetRange.contains(position.textRange) || targetRange.contains(position.textOffset)
	}

	private fun supportBuilderTypeTarget(position: PsiElement): KubeGroovyRegistryTarget? {
		val call = PsiTreeUtil.getParentOfType(position, GrCall::class.java, false) as? GrMethodCallExpression ?: return null
		val reference = call.invokedExpression as? GrReferenceExpression ?: return null
		if (reference.referenceName != "create") return null
		val qualifierType = reference.qualifierExpression?.type as? PsiClassType ?: return null
		if (qualifierType.resolve()?.qualifiedName != KubeGroovyNames.EVENT_TYPE) return null
		val eventElementType = qualifierType.parameters.singleOrNull() ?: return null
		val typeArgument = call.argumentList.expressionArguments.getOrNull(1) ?: return null
		val typeArgumentRange = typeArgument.textRange
		if (!typeArgumentRange.contains(position.textRange) && !typeArgumentRange.contains(position.textOffset)) return null
		return supportRegistryTargetForCreateCall(call, eventElementType)
	}

	private fun supportRegistryTargetForCreateCall(call: GrMethodCallExpression, eventElementType: PsiType): KubeGroovyRegistryTarget? {
		var current: PsiElement? = call.parent
		while (current != null) {
			val enclosingCall = current as? GrMethodCallExpression
			if (enclosingCall != null) {
				val reference = enclosingCall.invokedExpression as? GrReferenceExpression
				val qualifier = reference?.qualifierExpression
				if (reference?.referenceName == "registry"
				&& (qualifier?.text == KubeGroovyNames.STARTUP_EVENTS || qualifier?.text == KubeGroovyNames.STARTUP_EVENTS_ALIAS)
				) {
					val targetExpression = enclosingCall.argumentList.expressionArguments.firstOrNull()
					if (targetExpression != null) {
						supportRegistryTargetForExpression(targetExpression)?.let { return it }
					}
				}
			}
			current = current?.parent
		}
		val matchingTargets = KubeGroovyScriptData.registryTargets.filter {
			it.elementTypeName == eventElementType.canonicalText.replace('$', '.')
		}
		return matchingTargets.singleOrNull()
	}

	private fun supportRegistryTargetForExpression(target: GrExpression): KubeGroovyRegistryTarget? {
		val targetType = target.type as? PsiClassType
		if (targetType?.resolve()?.qualifiedName == KubeGroovyNames.RESOURCE_KEY) {
			val valueType = targetType.parameters.singleOrNull() as? PsiClassType
			val elementTypeName = if (valueType?.resolve()?.qualifiedName == KubeGroovyNames.REGISTRY) {
				valueType.parameters.singleOrNull()?.canonicalText
			} else valueType?.canonicalText
			val matches = elementTypeName?.let { elementName ->
				KubeGroovyScriptData.registryTargets.filter { it.elementTypeName == elementName.replace('$', '.') }
			}.orEmpty()
			return matches.singleOrNull()
		}
		val literal = (target as? GrLiteral) ?: PsiTreeUtil.findChildOfType(target, GrLiteral::class.java) ?: return null
		val key = literal.value as? String ?: return null
		val normalizedKey = if (key.contains(":")) key else "minecraft:$key"
		return KubeGroovyScriptData.registryTargets.firstOrNull { it.key == normalizedKey }
	}

	fun supportIsBuilderTypeArgument(position: PsiElement): Boolean = supportBuilderTypeTarget(position) != null

	fun supportScriptBindings(file: PsiFile): List<KubeGroovyBinding> =
		supportScriptTypeFor(file)?.let(KubeGroovyScriptData.bindingsByScriptType::get)
			?.takeIf { it.isNotEmpty() }
			?: KubeGroovyScriptData.bindingsByScriptType.values.flatten().distinctBy { it.name }

	private fun supportScriptEventMethods(file: PsiFile): List<KubeGroovyEventMethod> {
		val methods = supportScriptTypeFor(file)?.let { KubeGroovyScriptData.eventMethodsByScriptType[it] }
			?.takeIf { it.isNotEmpty() }
			?: KubeGroovyScriptData.eventMethodsByScriptType.values.flatten()
		return methods.orEmpty().distinct()
	}

	fun supportHasBindingPrefix(file: PsiFile, prefix: String): Boolean {
		if (supportScriptBindings(file).any { it.name.startsWith(prefix, ignoreCase = true) }) return true
		val scriptType = supportScriptTypeFor(file)
		if (scriptType != null && scriptType != "startup") return false
		return KubeGroovyNames.STARTUP_EVENTS.startsWith(prefix, ignoreCase = true)
			|| KubeGroovyNames.STARTUP_EVENTS_ALIAS.startsWith(prefix, ignoreCase = true)
	}

	private fun supportScriptTypeFor(file: PsiFile): String? {
		val path = (file.virtualFile?.path ?: file.originalFile.virtualFile?.path)
			?.replace('\\', '/')
			?.lowercase(Locale.ROOT)
			?: return null
		val normalizedPath = "/$path/"
		return listOf("startup", "server", "client").firstOrNull { "/${it}_scripts/" in normalizedPath }
	}

	private fun supportScriptBindingType(binding: KubeGroovyBinding): String = when {
		binding.eventGroup -> KubeGroovyNames.EVENT_GROUP_BINDING
		binding.classValue -> "java.lang.Class<${binding.typeName}>"
		else -> binding.typeName
	}

	private fun supportAddBoundMemberCompletions(parameters: CompletionParameters, result: CompletionResultSet) {
		val reference = PsiTreeUtil.getParentOfType(parameters.position, GrReferenceExpression::class.java, false) ?: return
		val qualifier = reference.qualifierExpression as? GrReferenceExpression ?: return
		if (parameters.offset <= qualifier.textRange.endOffset) return
		val file = parameters.originalFile
		val qualifierName = qualifier.text
		val binding = supportScriptBindings(file).firstOrNull { it.name == qualifierName }
			?: supportScriptBindings(file).firstOrNull { it.name.removePrefix("\u0024") == qualifierName }
			?: supportEventGroupName(file, qualifierName)?.let { groupName ->
				KubeGroovyBinding("\u0024${groupName}", KubeGroovyNames.EVENT_GROUP_BINDING, false, true)
			}
		if (binding?.eventGroup == true) {
			val groupName = supportEventGroupName(file, qualifierName) ?: return
			for (eventMethod in supportScriptEventMethods(file).filter { it.groupName == groupName }.distinctBy { it.name }) {
				result.addElement(
					LookupElementBuilder.create(eventMethod.name)
						.withIcon(AllIcons.Nodes.Method)
						.withTypeText(eventMethod.eventTypeName.substringAfterLast('.'), true)
						.withTailText("  KubeGroovy event", true)
						.withKubeGroovyPriority()
				)
			}
			if (groupName == "StartupEvents") {
				result.addElement(
					LookupElementBuilder.create("registry")
						.withIcon(AllIcons.Nodes.Method)
						.withTypeText("RegistryKubeEvent<T>", true)
						.withTailText("  registry event", true)
						.withKubeGroovyPriority()
				)
			}
			return
		}

		val resolvedBinding = binding ?: return
		val receiverClass = JavaPsiFacade.getInstance(parameters.position.project)
			.findClass(resolvedBinding.typeName, parameters.position.resolveScope) ?: return
		val isStaticBinding = resolvedBinding.classValue
		val nativeMethods = receiverClass.allMethods.asSequence()
			.filter { it.hasModifierProperty(PsiModifier.PUBLIC) }
			.filter { it.hasModifierProperty(PsiModifier.STATIC) == isStaticBinding }
			.filterNot { it.isConstructor }
			.filterNot { supportShouldSuppressRawMethod(parameters, it) }
			.distinctBy { method -> method.name + method.parameterList.parameters.joinToString { it.type.canonicalText } }
		for (method in nativeMethods) {
			val signature = method.parameterList.parameters.joinToString(", ") { it.type.presentableText }
			result.addElement(
				LookupElementBuilder.create(method.name)
					.withIcon(AllIcons.Nodes.Method)
					.withTypeText(method.returnType?.presentableText ?: "void", true)
					.withTailText("($signature)", true)
					.withKubeGroovyPriority()
			)
		}

		for (member in KubeGroovyScriptData.members) {
			if (member.receiverType != resolvedBinding.typeName || member.isStatic != isStaticBinding || member.constructor) continue
			val signature = member.parameters.joinToString(", ")
			result.addElement(
				LookupElementBuilder.create(member.name)
					.withIcon(AllIcons.Nodes.Method)
					.withTypeText(member.returnType, true)
					.withTailText("($signature)  KubeGroovy", true)
					.withKubeGroovyPriority()
			)
		}
	}

	private fun supportEventGroupName(file: PsiFile, qualifierText: String): String? {
		if (qualifierText == KubeGroovyNames.STARTUP_EVENTS || qualifierText == KubeGroovyNames.STARTUP_EVENTS_ALIAS) {
			return "StartupEvents"
		}
		val normalizedName = qualifierText.removePrefix("\u0024")
		return supportScriptBindings(file).firstOrNull {
			it.eventGroup && it.name.removePrefix("\u0024") == normalizedName
		}?.name?.removePrefix("\u0024")
			?: supportScriptEventMethods(file).firstOrNull { it.groupName == normalizedName }?.groupName
	}

	private fun supportBindingReferencePrefix(parameters: CompletionParameters): String? {
		val reference = PsiTreeUtil.getParentOfType(parameters.position, GrReferenceExpression::class.java, false) ?: return null
		if (reference.qualifierExpression != null) return null
		val referenceRange = reference.textRange
		val offset = parameters.offset
		if (offset < referenceRange.startOffset || offset > referenceRange.endOffset) return null
		val referenceText = reference.text
		val dummyIdentifier = referenceText.lowercase(Locale.ROOT).indexOf("intellijidearulezzz")
		val relativeOffset = (offset - referenceRange.startOffset).coerceIn(0, referenceText.length)
		val prefixEnd = minOf(relativeOffset, if (dummyIdentifier >= 0) dummyIdentifier else referenceText.length)
		return referenceText.substring(0, prefixEnd).takeIf { it.isNotEmpty() }
	}

	private fun supportErasedPsiTypeName(type: PsiType): String {
		val out = StringBuilder()
		var genericDepth = 0
		for (character in type.canonicalText) {
			when (character) {
				'<' -> genericDepth++
				'>' -> genericDepth--
				else -> if (genericDepth == 0) out.append(character)
			}
		}
		return out.toString().replace('$', '.')
	}

	private fun supportShouldSuppressRawMethod(parameters: CompletionParameters, element: PsiElement?): Boolean {
		val method = element as? PsiMethod ?: return false
		val reference = PsiTreeUtil.getParentOfType(parameters.position, GrReferenceExpression::class.java, false) ?: return false
		val qualifier = reference.qualifierExpression ?: return false
		val qualifierType = qualifier.type as? PsiClassType ?: return false
		val qualifierClass = qualifierType.resolve() ?: return false
		val receiverType = (if (qualifierClass.qualifiedName == "java.lang.Class") {
			(qualifierType.parameters.singleOrNull() as? PsiClassType)?.resolve()?.qualifiedName
		} else qualifierClass.qualifiedName) ?: return false
		val rawParameters = method.parameterList.parameters.map { supportErasedPsiTypeName(it.type) }
		return KubeGroovyScriptData.suppressedMethods.any { suppressed ->
			suppressed.receiverType == receiverType
				&& suppressed.name == method.name
				&& suppressed.parameters.map { it.replace('$', '.') } == rawParameters
		}
	}

	private fun supportStringPrefix(parameters: CompletionParameters): String {
		val literal = PsiTreeUtil.getParentOfType(parameters.position, GrLiteral::class.java, false) ?: return ""
		val literalRange = literal.textRange
		val literalText = literal.text
		if (literalText.length < 2 || (literalText.first() != '"' && literalText.first() != '\'')) return ""
		val contentEnd = if (literalText.length > 1 && literalText.last() == literalText.first()) literalText.length - 1 else literalText.length
		val dummyIdentifier = literalText.lowercase().indexOf("intellijidearulezzz")
		if (dummyIdentifier >= 0) return literalText.substring(1, dummyIdentifier)
		val prefixEnd = minOf(parameters.offset - literalRange.startOffset, contentEnd)
		if (prefixEnd <= 1) return ""
		return literalText.substring(1, prefixEnd)
	}

	private fun supportInsertRegistryString(context: com.intellij.codeInsight.completion.InsertionContext, element: LookupElement) {
		val target = registryTargetForKey(element.lookupString) ?: return
		supportInsertString(context, target.key.removePrefix("minecraft:"))
	}

	private fun supportInsertBuilderType(context: com.intellij.codeInsight.completion.InsertionContext, builderTypeId: String) {
		supportInsertString(context, builderTypeId)
	}

	private fun supportInsertString(context: com.intellij.codeInsight.completion.InsertionContext, value: String) {
		val caretElement = context.file.findElementAt(context.startOffset)
		val literal = caretElement?.let { PsiTreeUtil.getParentOfType(it, GrLiteral::class.java, false) }
		val replacementRange = literal?.textRange
			?: TextRange.create(context.startOffset, context.tailOffset)
		val replacementStart = replacementRange.startOffset
		val expression = "\"$value\""
		context.document.replaceString(replacementStart, replacementRange.endOffset, expression)
		context.editor.caretModel.moveToOffset(replacementStart + expression.length)
	}
}

