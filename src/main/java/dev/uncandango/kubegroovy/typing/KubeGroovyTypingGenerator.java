	/**
	 * Snapshots every event-group handler per script side for the LivePlugin
	 * events provider. Group keys are runtime binding names ({@code $}-prefixed,
	 * see BindingRegistry), matching the qualifier text scripts use.
	 */
	private static Map<ScriptType, Map<String, List<EventMethod>>> snapshotEventMethods() {
		var snapshot = new LinkedHashMap<ScriptType, Map<String, List<EventMethod>>>();
		var groups = EventGroups.ALL.get().map().values().stream()
			.sorted(Comparator.comparing(group -> group.name)).toList();
		for (var type : ScriptType.VALUES) {
			var byGroup = new LinkedHashMap<String, List<EventMethod>>();
			for (var group : groups) {
				var methods = describeEventMethods(group.getHandlers().values(), type);
				if (!methods.isEmpty()) byGroup.put("$" + group.name, methods);
			}
			snapshot.put(type, Map.copyOf(byGroup));
		}
		return Map.copyOf(snapshot);
	}

	/**
	 * Describes the synthetic static methods for one group's handlers on one
	 * script side, mirroring the runtime call shapes
	 * ({@code handler} or {@code target, handler}; see EventHandler.call) and
	 * the overload matrix the retired events GDSL used. Registry-shaped
	 * handlers (required {@code ResourceKey} target, single-type-variable
	 * event) collapse to one generic method instead, e.g.
	 * {@code static <T> void registry(ResourceKey<Registry<T>>,
	 * Consumer<RegistryKubeEvent<T>>)}.
	 */
	public static List<EventMethod> describeEventMethods(Collection<EventHandler> handlers, ScriptType type) {
		var out = new ArrayList<EventMethod>();
		if (handlers == null) return List.copyOf(out);
		for (var handler : handlers.stream().sorted(Comparator.comparing(h -> h.name)).toList()) {
			if (handler == null || handler.name == null || handler.name.isBlank()) continue;
			try {
				if (!handler.scriptTypePredicate.test(type)) continue;
			} catch (Throwable ignored) {
				continue;
			}
			String eventType;
			try {
				eventType = handler.eventType.get().getName();
			} catch (Throwable ignored) {
				eventType = Object.class.getName();
			}
			if (isGenericRegistryShape(handler)) {
				out.add(new EventMethod(handler.name, "void", List.of("T"), List.of(
					new EventMethodParam("registry",
						"net.minecraft.resources.ResourceKey<net.minecraft.core.Registry<T>>"),
					new EventMethodParam("consumer", "java.util.function.Consumer<" + eventType + "<T>>"))));
				continue;
			}
			var callback = "java.util.function.Consumer<" + eventType + ">";
			if (handler.target == null) {
				out.add(new EventMethod(handler.name, "void", List.of(),
					List.of(new EventMethodParam("handler", callback))));
			} else if (!handler.targetRequired) {
				out.add(new EventMethod(handler.name, "void", List.of(),
					List.of(new EventMethodParam("handler", callback))));
				out.add(new EventMethod(handler.name, "void", List.of(), List.of(
					new EventMethodParam("target", String.class.getName()),
					new EventMethodParam("handler", callback))));
				var target = handlerTarget(handler);
				if (!String.class.getName().equals(target)) {
					out.add(new EventMethod(handler.name, "void", List.of(), List.of(
						new EventMethodParam("target", target),
						new EventMethodParam("handler", callback))));
				}
			} else {
				out.add(new EventMethod(handler.name, "void", List.of(), List.of(
					new EventMethodParam("target", String.class.getName()),
					new EventMethodParam("handler", callback))));
				var target = handlerTarget(handler);
				if (!String.class.getName().equals(target)) {
					out.add(new EventMethod(handler.name, "void", List.of(), List.of(
						new EventMethodParam("target", target),
						new EventMethodParam("handler", callback))));
				}
			}
		}
		return List.copyOf(out);
	}

	/**
	 * Registry-shaped handlers take a {@code ResourceKey} target whose element
	 * is inferred from the call (the runtime coerces it), while the event type
	 * carries one type variable — so the editor model is a single generic
	 * method rather than the String/target overload pair.
	 */
	public static boolean isGenericRegistryShape(EventHandler handler) {
		try {
			if (handler == null || handler.target == null || !handler.targetRequired) return false;
			if (!"net.minecraft.resources.ResourceKey".equals(handlerTarget(handler))) return false;
			Class<?> raw;
			try {
				raw = handler.eventType.get();
			} catch (Throwable ignored) {
				return false;
			}
			return raw != null && raw.getTypeParameters().length == 1;
		} catch (Throwable ignored) {
			return false;
		}
	}

