	public static String renderGdsl(Path gameDir, Map<ScriptType, List<TypingBinding>> bindings) {
		var out = new StringBuilder();
		out.append("// ").append(GENERATED_MARKER).append('\n');
		out.append("// Activate this file in IntelliJ's Groovy settings after generation.\n\n");
		renderTypingContexts(out, false);
		for (var type : ScriptType.VALUES) {
			out.append("contributor(").append(type.name).append("Ctx) {\n");
			var descriptors = new TreeMap<String, TypingBinding>();
			for (var binding : bindings.getOrDefault(type, List.of())) {
				if (!binding.eventGroup()) descriptors.put(binding.name(), binding);
			}
			for (var binding : descriptors.values()) {
				var bindingType = binding.typeName();
				if (binding.classValue()) bindingType = "java.lang.Class<" + boxed(bindingType) + ">";
				out.append("  variable(name: '").append(groovy(binding.name())).append("', type: '").append(groovy(bindingType)).append("')\n");
			}
			out.append("  method(name: 'log', type: 'void', params: [value: 'java.lang.Object'])\n");
			out.append("}\n\n");
		}
		return out.toString();
	}

	/** Renders event-group variables and handler signatures independently from the normal script bindings. */
	public static String renderEventsGdsl(Path gameDir) {
		var groups = EventGroups.ALL.get();
		var entries = groups.map().entrySet().stream().sorted(Map.Entry.comparingByKey()).toList();
		var out = new StringBuilder();
		out.append("// ").append(GENERATED_MARKER).append('\n');
		out.append("// Activate this file in IntelliJ's Groovy settings after generation.\n\n");
		renderTypingContexts(out, true);
		for (var type : ScriptType.VALUES) {
			out.append("contributor(").append(type.name).append("Ctx) {\n");
			for (var entry : entries) {
				out.append("  variable(name: '").append(groovy(entry.getKey())).append("', type: '")
						.append(EVENT_GROUP_WRAPPER_TYPE).append("')\n");
			}
			out.append("}\n\n");

			for (var entry : entries) {
				var handlers = entry.getValue().getHandlers().values().stream()
					.filter(handler -> handler.scriptTypePredicate.test(type))
					.sorted(Comparator.comparing(handler -> handler.name))
					.toList();
				if (handlers.isEmpty()) continue;
				// EventGroupWrapper is the actual runtime type of every event-group binding.
				// The generated name must therefore be a real class; synthetic nested names
				// are not resolved by IntelliJ's ctype contributor.
				out.append("contributor(").append(type.name).append("EventCtx) {\n");
				out.append("  def __kgyQualifier = place?.qualifierExpression?.text\n");
				out.append("  if (__kgyQualifier != '").append(groovy(entry.getKey())).append("') return\n");
				for (var handler : handlers) renderEvent(out, handler, type);
				out.append("}\n\n");
			}
		}
		return out.toString();
	}

	private static void renderEvent(StringBuilder out, EventHandler handler, ScriptType type) {
		if (!handler.scriptTypePredicate.test(type)) return;
		String eventType;
		try { eventType = handler.eventType.get().getName(); } catch (Throwable ignored) { eventType = "java.lang.Object"; }
		var callback = "handler: '" + groovy("java.util.function.Consumer<" + eventType + ">") + "'";
		if (handler.target == null) {
			renderEventMethod(out, handler.name, callback, null);
		} else if (!handler.targetRequired) {
			renderEventMethod(out, handler.name, callback, null);
			renderEventMethod(out, handler.name, callback, String.class.getName());
			var target = handlerTarget(handler);
			if (!String.class.getName().equals(target)) renderEventMethod(out, handler.name, callback, target);
		} else {
			renderEventMethod(out, handler.name, callback, String.class.getName());
			var target = handlerTarget(handler);
			if (!String.class.getName().equals(target)) renderEventMethod(out, handler.name, callback, target);
		}
	}

	private static void renderEventMethod(StringBuilder out, String name, String callback, String target) {
		out.append("  method(name: '").append(groovy(name)).append("', type: 'void', params: [");
		if (target != null) out.append("target: '").append(groovy(target)).append("', ");
		out.append(callback).append("])\n");
	}

	private static void renderTypingContexts(StringBuilder out, boolean eventContexts) {
		out.append("def base = [scope: scriptScope(null), filetypes: [");
		for (int i = 0; i < ScriptManager.SUPPORTED_EXTENSIONS.size(); i++) {
			if (i > 0) out.append(", ");
			out.append('\'').append(groovy(ScriptManager.SUPPORTED_EXTENSIONS.get(i).substring(1))).append('\'');
		}
		out.append("]]\n");
		if (eventContexts) out.append("def eventType = [ctype: '").append(EVENT_GROUP_WRAPPER_TYPE).append("']\n");
		for (var type : ScriptType.VALUES) {
			out.append("def ").append(type.name).append("Regexp = [pathRegexp: \".*/").append(type.name).append("_scripts/.*\"]\n");
		}
		for (var type : ScriptType.VALUES) {
			out.append("def ").append(type.name).append("Ctx = context(base + ").append(type.name).append("Regexp)\n");
			if (eventContexts) {
				out.append("def ").append(type.name).append("EventCtx = context(base + ").append(type.name).append("Regexp + eventType)\n");
			}
		}
		out.append('\n');
	}

	private static String handlerTarget(EventHandler handler) {
		try {
			EventTargetType<?> target = handler.target;
			return target.describeType.asClass().getName();
		} catch (Throwable ignored) {
			return Object.class.getName();
		}
	}

	private static Set<Class<?>> interfacesOf(Class<?> type) {
		var result = new LinkedHashSet<Class<?>>();
		var queue = new ArrayDeque<Class<?>>();
		queue.add(type);
		while (!queue.isEmpty()) {
			var current = queue.removeFirst();
			for (var iface : current.getInterfaces()) if (result.add(iface)) queue.addLast(iface);
			if (current.getSuperclass() != null && current.getSuperclass() != Object.class) queue.addLast(current.getSuperclass());
		}
		return result;
	}

	private static String boxed(String type) {
		return switch (type) {
			case "boolean" -> Boolean.class.getName();
			case "byte" -> Byte.class.getName();
			case "short" -> Short.class.getName();
			case "int" -> Integer.class.getName();
			case "long" -> Long.class.getName();
			case "float" -> Float.class.getName();
			case "double" -> Double.class.getName();
			case "char" -> Character.class.getName();
			default -> type;
		};
	}

