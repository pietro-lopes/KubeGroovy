	private static void renderBridgeMembers(StringBuilder out) {
		var loader = KubeGroovyTypingGenerator.class.getClassLoader();
		for (var targetName : Arrays.stream(KubeGroovyMetaClassCreationHandle.INJECTED_TYPES_LAZY.get()).sorted().toList()) {
			try {
				var target = Class.forName(targetName, false, loader);
				if (target.isAnnotationPresent(HideFromGY.class)) continue;
				var methods = new TreeMap<String, BridgeMethod>();
				for (var iface : interfacesOf(target)) {
					for (var method : iface.getDeclaredMethods()) addBridgeMethod(methods, method, iface);
				}
				for (var method : target.getDeclaredMethods()) addBridgeMethod(methods, method, target);
				if (methods.isEmpty()) continue;
				out.append("contributor(context(ctype: '").append(groovy(targetName)).append("')) {\n");
				for (var bridge : methods.values()) {
					out.append("  method(name: '").append(groovy(bridge.name())).append("', type: '").append(groovy(bridge.returnType())).append("'");
					if (!bridge.parameters().isEmpty()) {
						out.append(", params: [");
						for (int i = 0; i < bridge.parameters().size(); i++) {
							if (i > 0) out.append(", ");
							out.append("arg").append(i).append(": '").append(groovy(bridge.parameters().get(i))).append("'");
						}
						out.append("]");
					}
					out.append(")\n");
					if (bridge.property() != null) out.append("  property(name: '").append(groovy(bridge.property())).append("', type: '").append(groovy(bridge.propertyType())).append("')\n");
				}
				out.append("}\n\n");
			} catch (Throwable ignored) {
			}
		}
	}

	private static void addBridgeMethod(Map<String, BridgeMethod> methods, Method method, Class<?> declaring) {
		if (!Modifier.isPublic(method.getModifiers()) || Modifier.isStatic(method.getModifiers()) || method.isSynthetic() || method.isBridge()
			|| method.isAnnotationPresent(HideFromGY.class) || declaring.isAnnotationPresent(HideFromGY.class)) return;
		var parameters = method.getParameterTypes();
		int start = parameters.length > 0 && Context.class.isAssignableFrom(parameters[0]) ? 1 : 0;
		var aliases = new LinkedHashSet<String>();
		aliases.add(method.getName());
		var remap = method.getAnnotation(RemapForGY.class);
		if (remap != null && !remap.value().isBlank()) aliases.add(remap.value());
		var prefix = prefixFor(declaring);
		if (prefix != null && !prefix.value().isBlank() && method.getName().startsWith(prefix.value())) aliases.add(method.getName().substring(prefix.value().length()));
		for (var alias : aliases) {
			if (alias.isBlank()) continue;
			var parameterNames = new ArrayList<String>();
			for (int i = start; i < parameters.length; i++) parameterNames.add(parameters[i].getTypeName());
			String property = propertyAlias(alias, parameterNames.size(), method.getReturnType());
			var propertyType = property == null ? null : (method.getName().startsWith("set") && start < parameters.length
				? parameters[start].getTypeName() : method.getReturnType().getTypeName());
			var bridge = new BridgeMethod(alias, method.getReturnType().getTypeName(), List.copyOf(parameterNames), property, propertyType);
			methods.putIfAbsent(alias + "(" + String.join(",", parameterNames) + ")", bridge);
		}
	}

	private static String propertyAlias(String name, int parameterCount, Class<?> returnType) {
		if (parameterCount != 0 && parameterCount != 1) return null;
		if (name.startsWith("get") && name.length() > 3 && parameterCount == 0 && returnType != void.class) return decap(name.substring(3));
		if (name.startsWith("is") && name.length() > 2 && parameterCount == 0 && (returnType == boolean.class || returnType == Boolean.class)) return decap(name.substring(2));
		if (name.startsWith("set") && name.length() > 3 && parameterCount == 1) return decap(name.substring(3));
		return null;
	}

	private static String decap(String value) {
		return value.isEmpty() ? value : Character.toLowerCase(value.charAt(0)) + value.substring(1);
	}

	private static RemapPrefixForGY prefixFor(Class<?> type) {
		var prefix = type.getAnnotation(RemapPrefixForGY.class);
		if (prefix != null) return prefix;
		for (var iface : type.getInterfaces()) {
			prefix = prefixFor(iface);
			if (prefix != null) return prefix;
		}
		return type.getSuperclass() == null ? null : prefixFor(type.getSuperclass());
	}

	private static Set<Class<?>> interfacesOf(Class<?> type) {
		var result = new LinkedHashSet<Class<?>>();
		var queue = new ArrayDeque<Class<?>>();
		queue.add(type);
		while (!queue.isEmpty()) {
			var current = queue.removeFirst();
			for (var iface : current.getInterfaces()) if (result.add(iface)) queue.addLast(iface);
			if (current.getSuperclass() != null && current.getSuperclass() != Object.class) queue.addLast(current.getSuperclass());
		}
		return result;
	}

	private static String boxed(String type) {
		return switch (type) {
			case "boolean" -> Boolean.class.getName();
			case "byte" -> Byte.class.getName();
			case "short" -> Short.class.getName();
			case "int" -> Integer.class.getName();
			case "long" -> Long.class.getName();
			case "float" -> Float.class.getName();
			case "double" -> Double.class.getName();
			case "char" -> Character.class.getName();
			default -> type;
		};
	}

	private static String modulesEntry() {
		return "file://$PROJECT_DIR$/.idea/kubegroovy.iml";
	}

	public static String mergeModules(String existing) throws IOException {
		if (existing == null) {
			return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<project version=\"4\">\n  <component name=\"ProjectModuleManager\">\n    <modules>\n      <module fileurl=\"" + modulesEntry() + "\" filepath=\"$PROJECT_DIR$/.idea/kubegroovy.iml\" />\n    </modules>\n  </component>\n</project>\n";
		}
		var document = parseXml(existing);
		var modulesNode = findModules(document);
		var moduleNodes = modulesNode == null ? null : modulesNode.getChildNodes();
		boolean exactEntry = false;
		if (moduleNodes != null) {
			for (int i = 0; i < moduleNodes.getLength(); i++) {
				var node = moduleNodes.item(i);
				if (node.getNodeType() != Node.ELEMENT_NODE || !"module".equals(node.getNodeName())) continue;
				var fileurl = node.getAttributes().getNamedItem("fileurl");
				var filepath = node.getAttributes().getNamedItem("filepath");
				var url = fileurl == null ? "" : fileurl.getNodeValue();
				var path = filepath == null ? "" : filepath.getNodeValue();
				boolean referencesTyping = url.endsWith("kubegroovy.iml") || path.endsWith("kubegroovy.iml");
				boolean exact = modulesEntry().equals(url) && "$PROJECT_DIR$/.idea/kubegroovy.iml".equals(path);
				if (referencesTyping && !exact) throw new IOException("modules.xml contains a conflicting kubegroovy.iml entry");
				if (exact) exactEntry = true;
			}
		}
		if (exactEntry) return existing;
		int close = existing.indexOf("</modules>");
		if (close < 0) throw new IOException("modules.xml has no <modules> element");
		String newline = existing.contains("\r\n") ? "\r\n" : "\n";
		String indent = "      ";
		var lines = existing.substring(0, close).split("\\R");
		for (int i = lines.length - 1; i >= 0; i--) {
			var line = lines[i];
			if (line.contains("<module")) { indent = line.substring(0, line.indexOf('<')); break; }
		}
		var insertion = indent + "<module fileurl=\"" + modulesEntry() + "\" filepath=\"$PROJECT_DIR$/.idea/kubegroovy.iml\" />" + newline;
		return existing.substring(0, close) + insertion + existing.substring(close);
	}

	public static String mergeMisc(String existing) throws IOException {
		if (existing == null) return renderMisc();
		parseMiscXml(existing);
		var replacement = "  " + projectRootManager();
		var matcher = java.util.regex.Pattern.compile("(?s)<component\\b(?=[^>]*\\bname\\s*=\\s*(['\"])ProjectRootManager\\1)[^>]*(?:/>|>.*?</component\\s*>)")
			.matcher(existing);
		if (matcher.find()) return existing.substring(0, matcher.start()) + replacement + existing.substring(matcher.end());
		int close = existing.lastIndexOf("</project>");
		if (close < 0) throw new IOException("misc.xml has no </project> element");
		String newline = existing.contains("\r\n") ? "\r\n" : "\n";
		String prefix = existing.substring(0, close);
		String separator = prefix.endsWith("\n") || prefix.endsWith("\r") ? "" : newline;
		return prefix + separator + replacement + newline + existing.substring(close);
	}

	private static String projectRootManager() {
		return "<component name=\"ProjectRootManager\" version=\"2\" languageLevel=\"JDK_25\" default=\"true\" project-jdk-name=\"25\" project-jdk-type=\"JavaSDK\" />";
	}

	private static Document parseXml(String xml) throws IOException {
		try {
			Document document = secureParse(xml);
			if (!"project".equals(document.getDocumentElement().getNodeName()) || findModules(document) == null) throw new IOException("modules.xml has an invalid IntelliJ structure");
			boolean moduleManager = false;
			var components = document.getElementsByTagName("component");
			for (int i = 0; i < components.getLength(); i++) {
				var component = components.item(i);
				var name = component.getAttributes().getNamedItem("name");
				if (name != null && "ProjectModuleManager".equals(name.getNodeValue())) {
					moduleManager = true;
					break;
				}
			}
			if (!moduleManager) throw new IOException("modules.xml has no ProjectModuleManager component");
			return document;
		} catch (IOException error) {
			throw error;
		} catch (Exception error) {
			throw new IOException("Malformed modules.xml", error);
		}
	}

	private static Document secureParse(String xml) throws Exception {
		var factory = DocumentBuilderFactory.newInstance();
		factory.setNamespaceAware(false);
		factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
		factory.setFeature("http://xml.org/sax/features/external-general-entities", false);
		factory.setFeature("http://xml.org/sax/features/external-parameter-entities", false);
		factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
		factory.setXIncludeAware(false);
		factory.setExpandEntityReferences(false);
		return factory.newDocumentBuilder().parse(new InputSource(new StringReader(xml)));
	}

	private static Document parseMiscXml(String xml) throws IOException {
		try {
			var document = secureParse(xml);
			if (!"project".equals(document.getDocumentElement().getNodeName())) throw new IOException("misc.xml has an invalid IntelliJ structure");
			return document;
		} catch (IOException error) {
			throw error;
		} catch (Exception error) {
			throw new IOException("Malformed misc.xml", error);
		}
	}

	private static void validateMisc(String xml) throws IOException {
		var manager = findComponent(parseMiscXml(xml), "ProjectRootManager");
		if (manager == null) throw new IOException("Generated misc.xml has no ProjectRootManager component");
		var attributes = manager.getAttributes();
		for (var entry : Map.of(
			"version", "2",
			"languageLevel", "JDK_25",
			"default", "true",
			"project-jdk-name", "25",
			"project-jdk-type", "JavaSDK").entrySet()) {
			var attribute = attributes.getNamedItem(entry.getKey());
			if (attribute == null || !entry.getValue().equals(attribute.getNodeValue())) {
				throw new IOException("Generated misc.xml has an invalid ProjectRootManager component");
			}
		}
	}

	private static void validateIml(String xml) throws IOException {
		try {
			var document = secureParse(xml);
			if (!"module".equals(document.getDocumentElement().getNodeName())
				|| document.getElementsByTagName("component").getLength() == 0
				|| document.getElementsByTagName("content").getLength() == 0
				|| document.getElementsByTagName("orderEntry").getLength() == 0) {
				throw new IOException("Generated kubegroovy.iml has an invalid IntelliJ structure");
			}
		} catch (IOException error) {
			throw error;
		} catch (Exception error) {
			throw new IOException("Generated kubegroovy.iml is not valid XML", error);
		}
	}

	private static void validateGdsl(String source, String fileName) throws IOException {
		try {
			new GroovyShell().parse(source);
		} catch (Throwable error) {
			throw new IOException("Generated " + fileName + " is not valid Groovy", error);
		}
	}

	private static Node findModules(Document document) {
		var components = document.getElementsByTagName("component");
		for (int i = 0; i < components.getLength(); i++) {
			var component = components.item(i);
			var name = component.getAttributes().getNamedItem("name");
			if (name == null || !"ProjectModuleManager".equals(name.getNodeValue())) continue;
			for (var child = component.getFirstChild(); child != null; child = child.getNextSibling()) {
				if (child.getNodeType() == Node.ELEMENT_NODE && "modules".equals(child.getNodeName())) return child;
			}
		}
		return null;
	}

	private static Node findComponent(Document document, String name) {
		var components = document.getElementsByTagName("component");
		for (int i = 0; i < components.getLength(); i++) {
			var component = components.item(i);
			var attribute = component.getAttributes().getNamedItem("name");
			if (attribute != null && name.equals(attribute.getNodeValue())) return component;
		}
		return null;
	}

	private static void guardGeneratedTarget(Path path) throws IOException {
		if (Files.isSymbolicLink(path)) throw new IOException("Refusing to replace symbolic-link typing target: " + path);
		if (Files.exists(path) && !Files.isRegularFile(path)) throw new IOException("Generated target is not a regular file: " + path);
		if (Files.exists(path) && !Files.readString(path, StandardCharsets.UTF_8).contains(GENERATED_MARKER)) {
			throw new IOException("Refusing to overwrite unmarked IntelliJ typing file: " + path);
		}
	}

	private static boolean writeChanged(Path path, String content) throws IOException {
		if (Files.exists(path) && Files.readString(path, StandardCharsets.UTF_8).equals(content)) return false;
		Files.createDirectories(path.getParent());
		var temporary = Files.createTempFile(path.getParent(), path.getFileName().toString(), ".tmp");
		try {
			Files.writeString(temporary, content, StandardCharsets.UTF_8);
			moveAtomically(temporary, path);
			return true;
		} finally {
			Files.deleteIfExists(temporary);
		}
	}

	private static void moveAtomically(Path source, Path target) throws IOException {
		try {
			Files.move(source, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
		} catch (AtomicMoveNotSupportedException error) {
			Files.move(source, target, StandardCopyOption.REPLACE_EXISTING);
		}
	}

	/** Writes a deterministic, generator-marked fallback jar and returns its path. */
	public static Path exportFallbackJar(Path cacheDirectory, String logicalName, Map<String, byte[]> entries) throws IOException {
		Files.createDirectories(cacheDirectory);
		var sorted = new TreeMap<String, byte[]>(entries);
		MessageDigest digest;
		try {
			digest = MessageDigest.getInstance("SHA-256");
		} catch (java.security.NoSuchAlgorithmException error) {
			throw new IOException("SHA-256 is unavailable", error);
		}
		for (var entry : sorted.entrySet()) {
			digest.update(entry.getKey().getBytes(StandardCharsets.UTF_8));
			digest.update((byte) 0);
			digest.update(entry.getValue());
		}
		var hash = hex(digest.digest()).substring(0, 24);
		var safe = (logicalName == null ? "content" : logicalName).replaceAll("[^A-Za-z0-9._-]", "_");
		var target = cacheDirectory.resolve(safe + "-" + hash + ".jar");
		if (Files.isSymbolicLink(target)) throw new IOException("Refusing to replace a symbolic-link typing cache jar: " + target);
		if (Files.exists(target)) {
			if (isGeneratorJar(target)) return target;
			throw new IOException("Refusing to overwrite an unmarked typing cache jar: " + target);
		}
		var temporary = Files.createTempFile(cacheDirectory, ".kubegroovy-typing-", ".tmp");
		try (var output = new ZipOutputStream(Files.newOutputStream(temporary))) {
			var marker = new ZipEntry("META-INF/kubegroovy-typing-cache.properties");
			marker.setTime(0);
			output.putNextEntry(marker);
			output.write(("generator=KubeGroovy\nlogical=" + logicalName + "\n").getBytes(StandardCharsets.UTF_8));
			output.closeEntry();
			for (var entry : sorted.entrySet()) {
				var zipEntry = new ZipEntry(entry.getKey());
				zipEntry.setTime(0);
				output.putNextEntry(zipEntry);
				output.write(entry.getValue());
				output.closeEntry();
			}
		}
		moveAtomically(temporary, target);
		return target;
	}

	/** Deletes only stale jars carrying the generator marker. */
	public static void pruneFallbackCache(Path cacheDirectory, Collection<Path> live) throws IOException {
		if (!Files.isDirectory(cacheDirectory)) return;
		var keep = live.stream().map(path -> path.toAbsolutePath().normalize()).collect(java.util.stream.Collectors.toSet());
		try (var files = Files.list(cacheDirectory)) {
			for (var file : files.filter(path -> path.toString().toLowerCase(Locale.ROOT).endsWith(".jar")).toList()) {
				if (keep.contains(file.toAbsolutePath().normalize()) || !isGeneratorJar(file)) continue;
				Files.deleteIfExists(file);
			}
		}
	}

	private static boolean isGeneratorJar(Path file) {
		try (var zip = new ZipFile(file.toFile())) {
			return zip.getEntry("META-INF/kubegroovy-typing-cache.properties") != null;
		} catch (IOException ignored) {
			return false;
		}
	}

	private static String hex(byte[] bytes) {
		var out = new StringBuilder(bytes.length * 2);
		for (var value : bytes) out.append(String.format(Locale.ROOT, "%02x", value));
		return out.toString();
	}

	private static String ideaUrl(Path path) {
		var absolute = path.toAbsolutePath().normalize();
		var raw = absolute.toUri().getPath();
		if (Files.isDirectory(absolute)) return "file://" + raw;
		if (raw.length() > 3 && raw.charAt(0) == '/' && raw.charAt(2) == ':') raw = raw.substring(1);
		return "jar://" + raw + "!/";
	}

	private static String xml(String value) {
		return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;").replace("'", "&apos;");
	}

	private static String groovy(String value) {
		var out = new StringBuilder(value.length() + 8);
		for (int i = 0; i < value.length(); i++) {
			char c = value.charAt(i);
			switch (c) {
				case '\\' -> out.append("\\\\");
				case '\'' -> out.append("\\'");
				case '\b' -> out.append("\\b");
				case '\t' -> out.append("\\t");
				case '\n' -> out.append("\\n");
				case '\f' -> out.append("\\f");
				case '\r' -> out.append("\\r");
				default -> {
					if (c < 0x20 || c == 0x2028 || c == 0x2029) out.append(String.format(Locale.ROOT, "\\u%04x", (int) c));
					else out.append(c);
				}
			}
		}
		return out.toString();
	}

	private static void ensureInside(Path root, Path path) throws IOException {
		if (!path.toAbsolutePath().normalize().startsWith(root)) throw new IOException("Typing output escaped the game directory");
	}

	private static void ensureNoSymlinkComponents(Path root, Path path) throws IOException {
		var normalizedRoot = root.toAbsolutePath().normalize();
		var normalizedPath = path.toAbsolutePath().normalize();
		if (!normalizedPath.startsWith(normalizedRoot)) throw new IOException("Typing output escaped the game directory");
		var current = normalizedRoot;
		for (var part : normalizedRoot.relativize(normalizedPath)) {
			current = current.resolve(part);
			if (Files.isSymbolicLink(current)) throw new IOException("Typing output contains a symbolic-link component: " + current);
		}
	}
