	@SuppressWarnings({"rawtypes", "unchecked"})
	private static void registerRegistrySuggestions(TypeSuggestionRegistry suggestions, Set<TypeInfo> registeredTypes,
		ResourceKey<?> key) {
		var registryType = RegistryType.ofKey((ResourceKey) key);
		if (registryType == null || !registeredTypes.add(registryType.type())) return;
		var elementType = registryType.type();
		suggestions.register(elementType, (cx, typeInfo) -> cx.lookupRegistry(typeInfo, null).entrySet().stream()
			.map(entry -> entry.getKey().identifier().toString()));
		suggestions.registerModifierFor(elementType, TagKey.class,
			(cx, typeInfo) -> cx.lookupRegistry(typeInfo, null).listTagIds()
				.map(tag -> tag.location().toString()));
	}

	private static TreeSet<String> snapshotStringWrapperNames(CommandSourceStack source) {
		var combined = new TypeWrappers();
		var managers = new LinkedHashSet<ScriptManager>();
		var startup = KubeGroovy.getStartupScriptManager();
		var client = KubeGroovy.getClientScriptManager();
		if (startup != null) managers.add(startup);
		try {
			var server = source.getServer().getServerResources().managers().kgy$getServerScriptManager();
			if (server != null) managers.add(server);
		} catch (Throwable error) {
			KubeGroovy.LOGGER.debug("Server script manager was unavailable while collecting string wrappers", error);
		}
		if (client != null) managers.add(client);
		for (var manager : managers) {
			var factory = manager.contextFactory;
			if (factory != null) combined.wrappers.putAll(factory.getTypeWrappers().wrappers);
		}
		return combined.wrappers.entrySet().stream()
			.filter(entry -> entry.getValue().explicitCoercions().stream().anyMatch(type -> type.asClass() == CharSequence.class))
			.map(entry -> entry.getKey().getName().replace('$', '.'))
			.collect(java.util.stream.Collectors.toCollection(TreeSet::new));
	}

