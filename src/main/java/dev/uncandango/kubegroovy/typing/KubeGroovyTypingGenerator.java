	private static String renderLivePluginEventData() {
		var out = new StringBuilder();
		var groups = EventGroups.ALL.get().map().values().stream().sorted(Comparator.comparing(group -> group.name)).toList();
		for (var type : ScriptType.VALUES) {
			out.append("\t").append(kotlinString(type.name)).append(" to listOf(\n");
			for (var group : groups) {
				var handlers = group.getHandlers().values().stream()
					.filter(handler -> handler.scriptTypePredicate.test(type))
					.filter(handler -> !("StartupEvents".equals(group.name) && "registry".equals(handler.name)))
					.sorted(Comparator.comparing(handler -> handler.name))
					.toList();
				for (var handler : handlers) {
					String eventType;
					try { eventType = handler.eventType.get().getName(); } catch (Throwable ignored) { eventType = Object.class.getName(); }
					var targetType = handlerTargetOrNull(handler);
					out.append("\t\tKubeGroovyEventMethod(")
						.append(kotlinString(group.name)).append(", ")
						.append(kotlinString(handler.name)).append(", ")
						.append(kotlinString(eventType)).append(", ")
						.append(targetType == null ? "null" : kotlinString(targetType)).append(", ")
						.append(handler.targetRequired).append("),\n");
				}
			}
			out.append("\t),\n");
		}
		return out.toString();
	}

	private static String handlerTargetOrNull(EventHandler handler) {
		if (handler.target == null) return null;
		try {
			return handler.target.describeType.asClass().getName();
		} catch (Throwable ignored) {
			return Object.class.getName();
		}
	}

	private static String kotlinString(String value) {
		var out = new StringBuilder(value.length() + 2).append('"');
		for (int i = 0; i < value.length(); i++) {
			char character = value.charAt(i);
			switch (character) {
				case '"' -> out.append("\\\"");
				case '\\' -> out.append("\\\\");
				case '$' -> out.append('\\').append("u0024");
				case '\n' -> out.append("\\n");
				case '\r' -> out.append("\\r");
				case '\t' -> out.append("\\t");
				default -> {
					if (Character.isISOControl(character)) {
						out.append('\\').append('u').append(String.format(Locale.ROOT, "%04x", (int) character));
					} else {
						out.append(character);
					}
				}
			}
		}
		return out.append('"').toString();
	}

