	private static String intellijConfigVersion(String name) {
		if (name.startsWith("IntelliJIdea") && name.length() > "IntelliJIdea".length()) return name.substring("IntelliJIdea".length());
		if (name.startsWith("IdeaIC") && name.length() > "IdeaIC".length()) return name.substring("IdeaIC".length());
		return null;
	}

	private static int compareIntellijConfigNames(String left, String right) {
		var leftVersion = intellijConfigVersion(left).split("\\.");
		var rightVersion = intellijConfigVersion(right).split("\\.");
		for (int i = 0; i < Math.max(leftVersion.length, rightVersion.length); i++) {
			int leftPart = i < leftVersion.length ? parseVersionPart(leftVersion[i]) : 0;
			int rightPart = i < rightVersion.length ? parseVersionPart(rightVersion[i]) : 0;
			int compared = Integer.compare(leftPart, rightPart);
			if (compared != 0) return compared;
		}
		// Prefer Ultimate if both products have the same IDE version.
		return Boolean.compare(right.startsWith("IntelliJIdea"), left.startsWith("IntelliJIdea"));
	}

	private static int parseVersionPart(String part) {
		try {
			return Integer.parseInt(part.replaceFirst("\\D.*$", ""));
		} catch (NumberFormatException ignored) {
			return 0;
		}
	}

