	private static int countBridgeMembers() {
		int count = 0;
		var loader = KubeGroovyTypingGenerator.class.getClassLoader();
		String[] injectedTypes;
		try {
			injectedTypes = KubeGroovyMetaClassCreationHandle.INJECTED_TYPES_LAZY.get();
		} catch (Throwable error) {
			KubeGroovy.LOGGER.debug("Unable to count injected bridge members outside a loaded mod environment", error);
			return 0;
		}
		for (var name : injectedTypes) {
			try {
				var type = Class.forName(name, false, loader);
				for (var iface : interfacesOf(type)) count += iface.getDeclaredMethods().length;
			} catch (Throwable ignored) {
			}
		}
		return count;
	}

	private record RuntimeRoots(List<Path> roots, List<Path> fallbacks) {
	}

	public static List<Path> collectRuntimeRoots() {
		return collectRuntimeRoots(null).roots();
	}

	private static RuntimeRoots collectRuntimeRoots(Path fallbackCache) {
		var fmlRoots = new LinkedHashSet<Path>();
		var fallbackRoots = new ArrayList<Path>();
		collectFmlRoots(fmlRoots, fallbackCache, fallbackRoots);
		var all = new LinkedHashSet<Path>(fmlRoots);
		collectClassLoaderRoots(all, KubeGroovyTypingGenerator.class.getClassLoader());
		collectPathProperty(all, "java.class.path");
		collectPathProperty(all, "jdk.module.path");
		var candidates = all.stream()
			.map(path -> path.toAbsolutePath().normalize())
			.filter(Files::isReadable)
			.filter(KubeGroovyTypingGenerator::classBearing)
			.filter(path -> !isNativeArtifact(path))
			.filter(path -> !isRawMinecraftDuplicate(path, fmlRoots))
			.toList();
		var deduplicated = new TreeMap<String, Path>(String.CASE_INSENSITIVE_ORDER);
		for (var path : candidates) deduplicated.putIfAbsent(path.toString(), path);
		var result = deduplicated.values().stream().sorted(PATH_ORDER).toList();
		return new RuntimeRoots(List.copyOf(result), List.copyOf(fallbackRoots));
	}

	private static void collectFmlRoots(Collection<Path> out, Path fallbackCache, Collection<Path> fallbackRoots) {
		try {
			for (var modFile : FMLLoader.getCurrent().getLoadingModList().getAllModFiles()) {
				try {
					JarContents contents = modFile.getContents();
					var roots = contents.getContentRoots();
					roots.forEach(out::add);
					boolean readable = roots.stream().anyMatch(path -> Files.isReadable(path) && classBearing(path));
					if (!readable && fallbackCache != null) {
						var entries = readJarContents(contents);
						if (!entries.isEmpty()) {
							var logicalName = modFile.getFileName();
							var fallback = exportFallbackJar(fallbackCache, logicalName == null ? "mod" : logicalName, entries);
							out.add(fallback);
							fallbackRoots.add(fallback);
						}
					}
				} catch (Throwable error) {
					KubeGroovy.LOGGER.debug("Unable to inspect one NeoForge content root", error);
				}
			}
		} catch (Throwable error) {
			KubeGroovy.LOGGER.debug("Unable to inspect NeoForge runtime roots", error);
		}
	}

	private static Map<String, byte[]> readJarContents(JarContents contents) {
		var entries = new TreeMap<String, byte[]>();
		try {
			contents.visitContent((name, resource) -> {
				if (name != null && name.endsWith(".class") && !name.startsWith("META-INF/versions/")) {
					try {
						entries.put(name, resource.readAllBytes());
					} catch (IOException ignored) {
					}
				}
			});
		} catch (Throwable ignored) {
		}
		return entries;
	}

	private static void collectClassLoaderRoots(Collection<Path> out, ClassLoader loader) {
		for (ClassLoader current = loader; current != null; current = current.getParent()) {
			if (current instanceof URLClassLoader urls) {
				for (URL url : urls.getURLs()) {
					if ("file".equalsIgnoreCase(url.getProtocol())) collectPathValues(Path.of(URI.create(url.toString())), out);
				}
			}
		}
		try {
			for (var resolved : ModuleLayer.boot().configuration().modules()) {
				resolved.reference().location().ifPresent(uri -> collectPathValues(uri, out));
			}
		} catch (Throwable ignored) {
			// A reduced test/runtime layer may not expose module locations.
		}
	}

	private static void collectPathProperty(Collection<Path> out, String property) {
		var value = System.getProperty(property, "");
		for (var item : value.split(java.util.regex.Pattern.quote(File.pathSeparator))) {
			if (!item.isBlank()) collectPathValues(item, out);
		}
	}

	private static void collectPathValues(Object value, Collection<Path> out) {
		if (value == null) return;
		if (value instanceof Path path) { out.add(path); return; }
		if (value instanceof File file) { out.add(file.toPath()); return; }
		if (value instanceof URI uri && "file".equalsIgnoreCase(uri.getScheme())) { out.add(Path.of(uri)); return; }
		if (value instanceof String string) { try { out.add(Path.of(string)); } catch (Exception ignored) { } return; }
		if (value instanceof Iterable<?> iterable) { iterable.forEach(item -> collectPathValues(item, out)); return; }
		if (value instanceof Object[] array) { for (var item : array) collectPathValues(item, out); }
	}

	private static boolean classBearing(Path path) {
		try {
			if (Files.isDirectory(path)) {
				try (var stream = Files.walk(path, 12)) {
					return stream.anyMatch(file -> Files.isRegularFile(file) && file.toString().endsWith(".class"));
				}
			}
			try (var zip = new ZipFile(path.toFile())) {
				var entries = zip.entries();
				while (entries.hasMoreElements()) {
					var name = entries.nextElement().getName();
					if (name.endsWith(".class")) return true;
				}
			}
		} catch (Exception ignored) {
		}
		return false;
	}

	private static boolean isNativeArtifact(Path path) {
		var name = path.getFileName() == null ? "" : path.getFileName().toString().toLowerCase(Locale.ROOT);
		return name.matches(".*(?:^|[-_.])natives(?:[-_.]|$).*");
	}

	private static boolean isRawMinecraftDuplicate(Path path, Collection<Path> canonicalRoots) {
		var normalized = path.toAbsolutePath().normalize();
		for (var canonical : canonicalRoots) {
			if (canonical.toAbsolutePath().normalize().equals(normalized)) return false;
		}
		if (!Files.isRegularFile(path)) return false;
		try (var zip = new ZipFile(path.toFile())) {
			boolean minecraft = zip.getEntry("net/minecraft/DetectedVersion.class") != null;
			boolean resources = false;
			var entries = zip.entries();
			while (entries.hasMoreElements()) {
				var name = entries.nextElement().getName();
				if (name.startsWith("assets/") || name.startsWith("data/")) {
					resources = true;
					break;
				}
			}
			boolean mod = zip.getEntry("META-INF/neoforge.mods.toml") != null || zip.getEntry("META-INF/mods.toml") != null;
			return minecraft && resources && !mod;
		} catch (Exception ignored) {
			return path.getFileName().toString().toLowerCase(Locale.ROOT).matches(".*(?:^|[-_.])client(?:[-_.]).*");
		}
	}

